        _w.Open("for (int i = 0; i < count; i++)");
        _w.Line($"if (!({Eq(element, "xi[i]", "yi[i]")})) return false;");
        _w.Close();
        _w.Line("return true;");
        _w.Close();

        _w.Open($"private static int GetHashCode_{type.ShortName}({p} o)");
        _w.Line("if (o is null) return 0;");
        EmitImmutablePreflightHash(element, "o");
        _w.Line($"{iface} oi = o;");
        _w.Line($"{KnownTypes.GlobalHashCode}.Streaming h = default;");
        _w.Line("int n = oi.Count;");
        _w.Open("for (int i = 0; i < n; i++)");
        _w.Line($"h.Add({ElementHashForContainer(type, element, "oi[i]")});");
        _w.Close();
        _w.Line("return h.ToHashCode();");
        _w.Close();

        if (type.HasShallowHash)
        {
            _w.Line($"private static int ShallowHashCode_{type.ShortName}({p} o) => o is null ? 0 : ((({iface})o).Count == 0 ? 1 : (({iface})o).Count);");
        }

        _w.Line();
    }

    private void EmitImmutablePreflight(TypeModel element, string x, string y)
    {
        if (!_model.Capabilities.HasImmutableArray)
        {
            return;
        }

        string immutable = $"global::System.Collections.Immutable.ImmutableArray<{element.GlobalName}>";
        _w.Line($"bool {x}Default = {x} is {immutable} i{x} && i{x}.IsDefault;");
        _w.Line($"bool {y}Default = {y} is {immutable} i{y} && i{y}.IsDefault;");
        _w.Line($"if ({x}Default || {y}Default) return {x}Default && {y}Default;");
    }

    private void EmitImmutablePreflightHash(TypeModel element, string o)
    {
        if (!_model.Capabilities.HasImmutableArray)
        {
            return;
        }

        _w.Line($"if ({o} is global::System.Collections.Immutable.ImmutableArray<{element.GlobalName}> io && io.IsDefault) return 0;");
    }

    private void EmitEnumerableCores(TypeModel type)
    {
        TypeModel element = T(type.ElementTypeId);
        string p = Param(type);
        string enumerable = $"global::System.Collections.Generic.IEnumerable<{element.GlobalName}>";

        _w.Open($"private static bool Equals_{type.ShortName}({p} x, {p} y{StateParam(type)})");
        _w.Line($"if ({RefEq("x", "y")}) return true;");
        _w.Line("if (x is null || y is null) return false;");
        EmitImmutablePreflight(element, "x", "y");
        _w.Line($"int xCount = x is global::System.Collections.Generic.ICollection<{element.GlobalName}> xc ? xc.Count : (x is global::System.Collections.Generic.IReadOnlyCollection<{element.GlobalName}> xr ? xr.Count : -1);");
        _w.Line($"int yCount = y is global::System.Collections.Generic.ICollection<{element.GlobalName}> yc ? yc.Count : (y is global::System.Collections.Generic.IReadOnlyCollection<{element.GlobalName}> yr ? yr.Count : -1);");
        _w.Line("if (xCount >= 0 && yCount >= 0 && xCount != yCount) return false;");
        if (type.IsGuarded)
        {
            _w.Line($"if (!state.TryEnter(Kind_{type.ShortName}, x, y)) return true;");
        }

        if (_model.Capabilities.HasFrameworkSpanHelpers)
        {
            _spanCores.Add(element.Id);
            _w.Line($"if ({KnownTypes.GlobalCollections}.TryGetSpan(x, out global::System.ReadOnlySpan<{element.GlobalName}> xs) && {KnownTypes.GlobalCollections}.TryGetSpan(y, out global::System.ReadOnlySpan<{element.GlobalName}> ys)) return Equals_SpanOf{element.ShortName}(xs, ys{(element.NeedsState ? ", ref state" : string.Empty)});");
        }

        _w.Line("int n = 0;");
        _w.Open($"using (global::System.Collections.Generic.IEnumerator<{element.GlobalName}> ex = (({enumerable})x).GetEnumerator())");
        _w.Open($"using (global::System.Collections.Generic.IEnumerator<{element.GlobalName}> ey = (({enumerable})y).GetEnumerator())");
        _w.Open("while (true)");
        _w.Line("bool mx = ex.MoveNext();");
        _w.Line("bool my = ey.MoveNext();");
        _w.Line("if (mx != my) return false;");
        _w.Line("if (!mx) break;");
        _w.Line($"if (!({Eq(element, "ex.Current", "ey.Current")})) return false;");
        _w.Line("n++;");
        _w.Close();
        _w.Close();
        _w.Close();
        _w.Line("if ((xCount >= 0 && n != xCount) || (yCount >= 0 && n != yCount)) throw new global::System.InvalidOperationException(\"A collection enumerated a different number of elements than its Count advertised.\");");
        _w.Line("return true;");
        _w.Close();

        _w.Open($"private static int GetHashCode_{type.ShortName}({p} o)");
        _w.Line("if (o is null) return 0;");
        EmitImmutablePreflightHash(element, "o");
        _w.Line($"{KnownTypes.GlobalHashCode}.Streaming h = default;");
        _w.Open($"foreach ({element.GlobalName} e in ({enumerable})o)");
        _w.Line($"h.Add({ElementHashForContainer(type, element, "e")});");
        _w.Close();
        _w.Line("return h.ToHashCode();");
        _w.Close();

        if (type.HasShallowHash)
        {
            _w.Open($"private static int ShallowHashCode_{type.ShortName}({p} o)");
            _w.Line("if (o is null) return 0;");
            _w.Line($"int count = o is global::System.Collections.Generic.ICollection<{element.GlobalName}> c ? c.Count : (o is global::System.Collections.Generic.IReadOnlyCollection<{element.GlobalName}> r ? r.Count : -1);");
            _w.Open("if (count < 0)");
            _w.Line("count = 0;");
            _w.Line($"foreach ({element.GlobalName} e in ({enumerable})o) count++;");
            _w.Close();
            _w.Line("return count == 0 ? 1 : count;");
            _w.Close();
        }

        _w.Line();
    }

