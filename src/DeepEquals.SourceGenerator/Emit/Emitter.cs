    private static string TupleItem(int index)
    {
        string path = string.Empty;
        while (index >= 7)
        {
            path += "Rest.";
            index -= 7;
        }

        return path + "Item" + (index + 1);
    }

    private void EmitProductCores(TypeModel type)
    {
        bool reference = type.Kind == TypeKind.Tuple;
        string p = reference ? Param(type) : type.GlobalName;
        List<(TypeModel Type, string Path, bool SameScc)> items = new List<(TypeModel, string, bool)>();
        if (type.Kind == TypeKind.KeyValuePair)
        {
            items.Add((T(type.KeyTypeId), "Key", type.KeyIsSameScc));
            items.Add((T(type.ValueTypeId), "Value", type.ValueIsSameScc));
        }
        else
        {
            for (int i = 0; i < type.ItemTypeIds.Count; i++)
            {
                items.Add((T(type.ItemTypeIds[i]), TupleItem(i), type.ItemsAreSameScc[i]));
            }
        }

        _w.Open($"private static bool Equals_{type.ShortName}({p} x, {p} y{StateParam(type)})");
        if (reference)
        {
            _w.Line($"if ({RefEq("x", "y")}) return true;");
            _w.Line("if (x is null || y is null) return false;");
            if (type.IsGuarded)
            {
                _w.Line($"if (!state.TryEnter(Kind_{type.ShortName}, x, y)) return true;");
            }
        }

        EmitPredicates(items.Select(i => Eq(i.Type, "x." + i.Path, "y." + i.Path)).ToList(), terminalReturnTrue: true);
        _w.Close();

        for (int level = 1; level >= (type.HasShallowHash ? 0 : 1); level--)
        {
            string name = (level == 1 ? "GetHashCode_" : "ShallowHashCode_") + type.ShortName;
            _w.Open($"private static int {name}({p} o)");
            if (reference)
            {
                _w.Line("if (o is null) return 0;");
            }

            List<string> inputs = new List<string>();
            foreach ((TypeModel itemType, string path, bool sameScc) in items)
            {
                string? hash = HashOrOmit(itemType, "o." + path, level, sameScc);
                if (hash is not null)
                {
                    inputs.Add(hash);
                }
            }

            _w.Line($"return {Combine(inputs)};");
            _w.Close();
        }

        _w.Line();
    }

    // ----- accessors ------------------------------------------------------------------------------------------------------------

    private void EmitAccessors()
    {
        HashSet<string> emitted = new HashSet<string>(StringComparer.Ordinal);
        Dictionary<string, List<MemberModel>> generic = new Dictionary<string, List<MemberModel>>(StringComparer.Ordinal);
        foreach (TypeModel type in _types)
        {
            foreach (MemberModel member in type.Members)
            {
                if (member.Access != MemberAccess.UnsafeAccessor)
                {
                    continue;
                }

                if (member.GenericAccessor)
                {
                    if (!generic.TryGetValue(member.GenericHolderName, out List<MemberModel>? list))
                    {
                        generic[member.GenericHolderName] = list = new List<MemberModel>();
                    }

                    if (!list.Any(m => m.AccessorName == member.AccessorName))
                    {
                        list.Add(member);
                    }

                    continue;
                }

                if (!emitted.Add(member.AccessorName))
                {
                    continue;
                }

                TypeModel fieldType = T(member.TypeId);
                string receiver = member.DeclaringTypeIsValueType ? $"ref {member.DeclaringTypeGlobalName} o" : $"{member.DeclaringTypeGlobalName} o";
                _w.Line($"[{KnownTypes.GlobalUnsafeAccessor}({KnownTypes.GlobalUnsafeAccessorKind}.Field, Name = \"{member.FieldMetadataName}\")]");
                _w.Line($"private static extern ref {Param(fieldType)} {member.AccessorName}({receiver});");
            }
        }

        if (emitted.Count > 0)
        {
            _w.Line();
        }

        // The runtime maps the holder's class type parameters onto the declaring type's, so one holder per definition
        // carries every accessor of that definition; call sites name the constructed arguments.
        foreach (KeyValuePair<string, List<MemberModel>> holder in generic.OrderBy(h => h.Key, StringComparer.Ordinal))
        {
            MemberModel first = holder.Value[0];
            _w.Open($"private static class {holder.Key}{first.GenericTypeParameters}{first.GenericConstraints}");
            foreach (MemberModel member in holder.Value.OrderBy(m => m.AccessorName, StringComparer.Ordinal))
            {
                string openReceiver = member.DeclaringTypeIsValueType ? $"ref {member.OpenDeclaringTypeGlobalName} o" : $"{member.OpenDeclaringTypeGlobalName} o";
                _w.Line($"[{KnownTypes.GlobalUnsafeAccessor}({KnownTypes.GlobalUnsafeAccessorKind}.Field, Name = \"{member.FieldMetadataName}\")]");
                _w.Line($"internal static extern ref {member.OpenFieldTypeGlobalName} {member.AccessorName}({openReceiver});");
            }

            _w.Close();
            _w.Line();
        }
    }

    private void EmitAccessorHolders()
    {
        foreach (AccessorHolderModel holder in _model.AccessorHolders)
        {
            if (_model.Capabilities.HasRequiresUnreferencedCode)
            {
                _w.Line("[global::System.Diagnostics.CodeAnalysis.RequiresUnreferencedCode(\"Reads private fields by name through reflection-built delegates.\")]");
            }

            if (_model.Capabilities.HasRequiresDynamicCode)
            {
                _w.Line("[global::System.Diagnostics.CodeAnalysis.RequiresDynamicCode(\"Compiles expression trees for private field access.\")]");
            }

            _w.Open($"private static class {holder.HolderName}");
            _w.Line($"static {holder.HolderName}() {{ }}");
            foreach (MemberModel member in holder.Members)
            {
                TypeModel fieldType = T(member.TypeId);
                string getter = $"{KnownTypes.GlobalFieldGetter}<{holder.DeclaringTypeGlobalName}, {Param(fieldType)}>";
                _w.Line($"private static readonly {getter} s_{member.AccessorName} = {KnownTypes.GlobalReflection}.CreateFieldGetter<{holder.DeclaringTypeGlobalName}, {Param(fieldType)}>(typeof({holder.DeclaringTypeGlobalName}), \"{member.FieldMetadataName}\");");
                _w.Line(holder.DeclaringTypeIsValueType
                    ? $"internal static {Param(fieldType)} {member.AccessorName}(ref {holder.DeclaringTypeGlobalName} o) => s_{member.AccessorName}(ref o);"
                    : $"internal static {Param(fieldType)} {member.AccessorName}({holder.DeclaringTypeGlobalName} o) => s_{member.AccessorName}(ref o);");
            }

            _w.Close();
            _w.Line();
        }
    }

    private void EmitCustomComparerHolders()
    {
        foreach (CustomComparerModel custom in _model.CustomComparers)
        {
            string fieldType = custom.HolderTypedAsComparer ? custom.ComparerTypeGlobalName : $"{KnownTypes.GlobalIEqualityComparer}<{custom.TargetTypeGlobalName}>";
            _w.Open($"private static class {custom.HolderName}");
            _w.Line($"static {custom.HolderName}() {{ }}");
            _w.Line($"internal static readonly {fieldType} Value = {custom.AcquisitionExpression};");
            _w.Close();
            _w.Line();
        }
    }
}

