    private void EmitUnorderedCores(TypeModel type)
    {
        bool dictionary = type.Kind == TypeKind.Dictionary;
        TypeModel key = dictionary ? T(type.KeyTypeId) : T(type.ElementTypeId);
        TypeModel? value = dictionary ? T(type.ValueTypeId) : null;
        string elementName = dictionary ? $"global::System.Collections.Generic.KeyValuePair<{key.GlobalName}, {value!.GlobalName}>" : key.GlobalName;
        string p = Param(type);
        string iface = type.CollectionInterfaceGlobalName.Length > 0 ? type.CollectionInterfaceGlobalName : type.GlobalName;
        bool anySameScc = dictionary ? (type.KeyIsSameScc || type.ValueIsSameScc) : type.ElementIsSameScc;
        string ops = type.ShortName + "Ops";

        _w.Open($"private static bool Equals_{type.ShortName}({p} x, {p} y{StateParam(type)})");
        _w.Line($"if ({RefEq("x", "y")}) return true;");
        _w.Line("if (x is null || y is null) return false;");
        _w.Line($"{iface} xi = x;");
        _w.Line($"{iface} yi = y;");
        _w.Line("int count = xi.Count;");
        _w.Line("if (count != yi.Count) return false;");
        if (!dictionary && key.Kind == TypeKind.Leaf && key.DefaultCompatible && key.LeafRule != LeafRule.Custom)
        {
            string hashSet = $"global::System.Collections.Generic.HashSet<{key.GlobalName}>";
            _w.Line($"if (x is {hashSet} hx && y is {hashSet} hy && {RefEq("hx.Comparer", $"{KnownTypes.GlobalEqualityComparer}<{key.GlobalName}>.Default")} && {RefEq("hy.Comparer", $"{KnownTypes.GlobalEqualityComparer}<{key.GlobalName}>.Default")}) return hx.SetEquals(hy);");
        }

        if (type.IsGuarded)
        {
            _w.Line($"if (!state.TryEnter(Kind_{type.ShortName}, x, y)) return true;");
        }

        string call = dictionary
            ? $"{KnownTypes.GlobalUnordered}.DictionaryEquals<{key.GlobalName}, {value!.GlobalName}, {ops}>(xi, yi, count, MaxUnorderedCollisionRun{StateArg(type)})"
            : $"{KnownTypes.GlobalUnordered}.SetEquals<{key.GlobalName}, {ops}>(xi, yi, count, MaxUnorderedCollisionRun{StateArg(type)})";
        _w.Line($"return {call};");
        _w.Close();

        // Ops struct: equality and full hash of one entry.
        string opsInterface = type.NeedsState ? KnownTypes.GlobalElementOps : KnownTypes.GlobalStatelessElementOps;
        _w.Open($"private struct {ops} : {opsInterface}<{elementName}>");
        string stateParam = type.NeedsState ? $", ref {KnownTypes.GlobalState} state" : string.Empty;
        string entryEq = dictionary
            ? $"{Eq(key, "a.Key", "b.Key")} && {Eq(value!, "a.Value", "b.Value")}"
            : Eq(key, "a", "b");
        _w.Line($"public bool Equals({elementName} a, {elementName} b{stateParam}) => {entryEq};");
        _w.Line($"public int GetHashCode({elementName} a) => {EntryHash(type, key, value, "a", level: 1, forMatching: true)};");
        _w.Close();

        // Level 1 hash: Combine(Count, sum of entry hashes) with empty-zero finalization.
        _w.Open($"private static int GetHashCode_{type.ShortName}({p} o)");
        _w.Line("if (o is null) return 0;");
        _w.Line($"{iface} oi = o;");
        _w.Line("int count = oi.Count;");
        _w.Line("int sum = 0;");
        string concrete = dictionary
            ? $"global::System.Collections.Generic.Dictionary<{key.GlobalName}, {value!.GlobalName}>"
            : $"global::System.Collections.Generic.HashSet<{key.GlobalName}>";
        _w.Open($"if (o is {concrete} known)");
        _w.Line($"foreach ({elementName} e in known) {{ unchecked {{ sum += {EntryHash(type, key, value, "e", level: 1, forMatching: false)}; }} }}");
        _w.Close();
        _w.Open("else");
        _w.Line($"foreach ({elementName} e in (global::System.Collections.Generic.IEnumerable<{elementName}>)o) {{ unchecked {{ sum += {EntryHash(type, key, value, "e", level: 1, forMatching: false)}; }} }}");
        _w.Close();
        _w.Line($"int h = {KnownTypes.GlobalHashCode}.Combine(count, sum);");
        _w.Line("return count == 0 && h == 0 ? 1 : h;");
        _w.Close();

        if (type.HasShallowHash)
        {
            _w.Line($"private static int ShallowHashCode_{type.ShortName}({p} o) => o is null ? 0 : ((({iface})o).Count == 0 ? 1 : (({iface})o).Count);");
        }

        _w.Line();
    }

    /// <summary>The hash of one set element or dictionary pair. Matching uses full element hashes; the container hash uses the SCC level.</summary>
    private string EntryHash(TypeModel container, TypeModel key, TypeModel? value, string entry, int level, bool forMatching)
    {
        if (value is null)
        {
            return forMatching ? (HashOrOmit(key, entry, 1, sameScc: false) ?? "0") : ElementHashForContainer(container, key, entry);
        }

        string k = forMatching ? (HashOrOmit(key, entry + ".Key", 1, sameScc: false) ?? "0") : (HashOrOmit(key, entry + ".Key", 1, container.KeyIsSameScc) ?? "0");
        string v = forMatching ? (HashOrOmit(value, entry + ".Value", 1, sameScc: false) ?? "0") : (HashOrOmit(value, entry + ".Value", 1, container.ValueIsSameScc) ?? "0");
        return $"{KnownTypes.GlobalHashCode}.Combine({k}, {v})";
    }

