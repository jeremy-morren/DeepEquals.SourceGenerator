namespace DeepEquals.SourceGenerator.Emit;

/// <summary>
/// A straight walk over the model.
/// No decisions are made here that the model does not already record.
/// </summary>
internal sealed class Emitter
{
    private const int MaxCombineArity = 32;

    private readonly ContextModel _model;
    private readonly CancellationToken _cancellationToken;
    private readonly TypeModel[] _types;
    private readonly HashSet<int> _spanCores = [];

    /// <summary>Bit-block structs whose runtime size flag some emitted path reads; the flags go in the context file.</summary>
    private readonly SortedSet<int> _blockGuards = [];
    private readonly List<(TypeModel Type, List<DispatchCase> Exact)> _pendingDispatchHolders = [];

    /// <summary>The writer of the file being emitted; every emit method writes here, and the file loop swaps it.</summary>
    private CodeWriter _w;

    private Emitter(ContextModel model, CancellationToken cancellationToken)
    {
        _model = model;
        _cancellationToken = cancellationToken;
        _types = model.Types.ToArray();
        _w = new CodeWriter(0);
    }

    /// <summary>
    /// The files of a context, the layout System.Text.Json uses: the context file carries what is shared, and each
    /// closure type that has anything to emit gets a file of its own.
    /// </summary>
    public static IReadOnlyList<GeneratedFile> Emit(ContextModel model, CancellationToken cancellationToken)
    {
        var emitter = new Emitter(model, cancellationToken);
        return emitter.EmitFiles();
    }

    private TypeModel Type(int id) => _types[id];

    private bool Annotations => _model.Capabilities.NullableAnnotations;

    // ----- file ---------------------------------------------------------------------------------------------------------

    /// <summary>The package version of the generator, as the header states it.</summary>
    private static string GeneratorVersion => GeneratorInfo.Version;

    /// <summary>The header template, an embedded resource with <c>{{placeholders}}</c>, read once and split into lines.</summary>
    private static readonly string[] HeaderTemplate = ReadHeaderTemplate();

    private static string[] ReadHeaderTemplate()
    {
        using var stream = typeof(Emitter).Assembly.GetManifestResourceStream("DeepEquals.SourceGenerator.Templates.AutoGeneratedHeader.cs");
        if (stream is null)
            throw new InvalidOperationException("The embedded header template 'Templates/AutoGeneratedHeader.cs' is missing from the generator assembly.");

        using var reader = new System.IO.StreamReader(stream);
        var lines = reader.ReadToEnd().Replace("\r\n", "\n").TrimEnd('\n').Split('\n');
        if (Array.IndexOf(lines, "/*") < 0 || Array.IndexOf(lines, "*/") < Array.IndexOf(lines, "/*"))
            throw new InvalidOperationException("The header template must hold its context description in a '/*' ... '*/' block on lines of their own.");

        if (Array.IndexOf(lines, "// </auto-generated>") < 0)
            throw new InvalidOperationException("The header template must close its notice with '// </auto-generated>' on a line of its own.");

        return lines;
    }

    private const string CommentIndent = "    ";

    /// <summary>
    /// A name for the block comment: no <c>global::</c>, and no <c>*/</c> that would end the comment early.
    /// </summary>
    private static string Display(string globalName) => 
        globalName.Replace("global::", string.Empty).Replace("*/", "* /");

    /// <summary>
    /// One indented line per entry, or a single "none" line,
    /// for a list placeholder inside the header's block comment.
    /// </summary>
    private static string CommentList(IEnumerable<string> entries, string none = "none")
    {
        var lines = entries.ToArray();
        return lines.Length == 0 
            ? CommentIndent + none 
            : string.Join("\n", lines.Select(l => CommentIndent + l));
    }

    /// <summary>
    /// Every value the header template can ask for, computed once from the model alone so output stays deterministic.
    /// Only the context file shows them all; a type file takes the notice and the directives.
    /// </summary>
    private Dictionary<string, string>? _headerValues;

    private Dictionary<string, string> HeaderValues()
    {
        // The comment shows the names as written, without the escaping the declarations need.
        var contextName = (_model.Namespace.Length > 0 ? $"{_model.Namespace}.{_model.Name}" : _model.Name).Replace("@", string.Empty);
        var c = _model.Capabilities;
        var o = _model.Options;

        (string Name, bool Present)[] capabilities =
        [
            ("ReadOnlySpan<T>", c.HasReadOnlySpan),
            ("Memory<T>", c.HasMemory),
            ("CollectionsMarshal.AsSpan", c.HasCollectionsMarshal),
            ("MemoryMarshal", c.HasMemoryMarshal),
            ("IReadOnlySet<T>", c.HasIReadOnlySet),
            ("ImmutableArray<T>", c.HasImmutableArray),
            ("ImmutableArray<T>.AsSpan", c.HasImmutableArrayAsSpan),
            ("[UnsafeAccessor]", c.HasUnsafeAccessor),
            ("[UnsafeAccessor] on generic types", c.HasGenericUnsafeAccessor),
            ("framework TryGetSpan/HashSpan", c.HasFrameworkSpanHelpers),
            ("framework Hash(Int128)", c.HasFrameworkHash128),
            ("Nullable.GetValueRefOrDefaultRef", c.HasNullableGetValueRefOrDefaultRef),
            ("decimal.GetBits(Span<int>)", c.HasDecimalGetBitsSpan),
            ("framework bit blocks", c.BitBlocks),
            ("[RequiresUnreferencedCode]", c.HasRequiresUnreferencedCode),
            ("[RequiresDynamicCode]", c.HasRequiresDynamicCode),
            ("[UnconditionalSuppressMessage]", c.HasUnconditionalSuppressMessage)
        ];

        // Generated code is written to raise no warning of its own; the tests compile every generated file at the highest
        // warning level with documentation diagnostics and fail on any. What remains are the warnings the compared
        // types' own APIs raise, which the consuming project already accepted by using them.
        static string Pragmas(IEnumerable<SuppressedDiagnostic> diagnostics) =>
            string.Join("\n", diagnostics.OrderBy(d => d.Id, StringComparer.Ordinal).Select(d => $"#pragma warning disable {d.Id} // {d.Reason}"));

        return new Dictionary<string, string>(StringComparer.Ordinal)
        {
            ["Version"] = GeneratorVersion,
            ["ContextName"] = contextName,
            ["ContextShortName"] = _model.Name,
            ["ContextAccessibility"] = _model.Accessibility,
            ["Roots"] = CommentList(_types.Where(t => t.IsRoot).Select(t => Display(t.GlobalName))),
            ["CustomComparers"] = CommentList(_model.CustomComparers.Select(cc => $"{Display(cc.TargetTypeGlobalName)}  by {Display(cc.ComparerTypeGlobalName)}{(cc.HandleNulls ? ", handles null itself" : string.Empty)}")),
            ["FileNotice"] = string.Empty,
            ["MaxSwitchCases"] = o.MaxSwitchCases.ToString(System.Globalization.CultureInfo.InvariantCulture),
            ["MaxUnorderedCollisionRun"] = o.MaxUnorderedCollisionRun.ToString(System.Globalization.CultureInfo.InvariantCulture),
            ["MaxComparisonPairs"] = o.MaxComparisonPairs.ToString("N0", System.Globalization.CultureInfo.InvariantCulture) + (o.CycleHandling switch
            {
                CycleHandling.Path => " (under Path: the ancestors of the pair being compared)",
                CycleHandling.Tree => " (not used under Tree)",
                _ => string.Empty,
            }),
            ["MaxBinaryExpressionArity"] = o.MaxBinaryExpressionArity.ToString(System.Globalization.CultureInfo.InvariantCulture),
            ["StructPassByValueMaxByteSize"] = o.StructPassByValueMaxByteSize.ToString(System.Globalization.CultureInfo.InvariantCulture),
            ["ExcludeInterfacesByPrefix"] = o.ExcludeInterfacesByPrefix.Count == 0 ? "(none)" : string.Join(", ", o.ExcludeInterfacesByPrefix),
            ["CycleHandling"] = o.CycleHandling.ToString(),
            ["MaxDepth"] = o.IsTree ? o.MaxDepth.ToString("N0", System.Globalization.CultureInfo.InvariantCulture) : $"{o.MaxDepth.ToString("N0", System.Globalization.CultureInfo.InvariantCulture)} (not used under {o.CycleHandling})",
            ["MatchingHashDepth"] = o.IsTree ? $"{o.MatchingHashDepth} (not used under Tree: the fingerprint is the full hash)" : o.MatchingHashDepth.ToString(System.Globalization.CultureInfo.InvariantCulture),
            ["LanguageVersion"] = $"{c.LanguageVersion / 100}.{c.LanguageVersion % 100}",
            ["CapabilitiesPresent"] = string.Join(", ", capabilities.Where(x => x.Present).Select(x => x.Name)).OrDefault("(none)"),
            ["CapabilitiesAbsent"] = string.Join(", ", capabilities.Where(x => !x.Present).Select(x => x.Name)).OrDefault("(none)"),
            ["Diagnostics"] = CommentList(_model.Diagnostics.Select(d => 
                $"{d.Descriptor.Id}: {string.Format(System.Globalization.CultureInfo.InvariantCulture, d.Descriptor.MessageFormat.ToString(System.Globalization.CultureInfo.InvariantCulture), d.Arguments.Cast<object>().ToArray()).Replace("*/", "* /")}")),
            ["UserSuppressions"] = Pragmas(_model.SuppressedDiagnostics),
            ["NullableDirective"] = Annotations
                ? "#nullable enable"
                : string.Empty,
        };
    }

    /// <summary>
    /// The trimming notice of a type whose comparison reads private fields through reflection-built delegates, itself or
    /// through a type it reaches: it goes in that type's own file, below the auto-generated notice, and names the
    /// attributes its public comparer carries. Starts with a newline, so the header keeps a blank line before it.
    /// </summary>
    private string TrimmingNotice(TypeModel type)
    {
        var reason = type.Members.Any(m => m.Access == MemberAccess.Delegate)
            ? "its private fields are read through reflection-built delegates"
            : "it reaches types whose private fields are read through reflection-built delegates";

        var attributes = new List<string>(2);
        if (_model.Capabilities.HasRequiresUnreferencedCode)
            attributes.Add("[RequiresUnreferencedCode]");

        if (_model.Capabilities.HasRequiresDynamicCode)
            attributes.Add("[RequiresDynamicCode]");

        var notice = $"\n// Trimming: {Display(type.GlobalName)} is compared through delegate field accessors:\n// {reason}, and trimming can remove those fields.";
        if (type.EmitWrapper && attributes.Count > 0)
            notice += $"\n// Its public comparer is marked {string.Join(" and ", attributes)}.";

        return notice;
    }

    /// <summary>
    /// Writes the header. The context file gets all of it; a type file gets the one-line <c>// &lt;auto-generated/&gt;</c>
    /// marker, which tools read as the full notice, and the compiler directives. The notice's text, the generator's
    /// version and the block comment describing the context live in the context file alone; each comparer class also
    /// carries the version in its <c>[GeneratedCode]</c>.
    /// </summary>
    private void EmitHeader(Dictionary<string, string> values, bool contextFile)
    {
        var noticeEnd = Array.IndexOf(HeaderTemplate, "// </auto-generated>");
        var infoStart = Array.IndexOf(HeaderTemplate, "/*");
        var infoEnd = Array.IndexOf(HeaderTemplate, "*/");
        if (!contextFile)
            _w.Line("// <auto-generated/>");

        for (var i = 0; i < HeaderTemplate.Length; i++)
        {
            // The notice, then the block comment and the blank line after it.
            if (!contextFile && (i <= noticeEnd || i >= infoStart && i <= infoEnd + 1))
                continue;

            var templateLine = HeaderTemplate[i];
            var line = values.Aggregate(
                templateLine,
                (current, value) => current.Replace("{{" + value.Key + "}}", value.Value));

            if (line.Length == 0 && templateLine.Length > 0)
                continue; // a placeholder that expanded to nothing leaves no blank line behind

            foreach (var part in line.Split('\n'))
                _w.Line(part);
        }
    }

    /// <summary>
    /// One file being written: its class body only, at the body's indentation. The header and the skeleton around
    /// it are written when the file closes, and only for a body that received something, so a type with nothing to
    /// emit costs neither a header nor a file. The body stays open until every body is complete, because a span core
    /// lands in its element's file only once the containers that call it have been emitted.
    /// </summary>
    private sealed class OpenFile
    {
        public OpenFile(string hintName, TypeModel? type, CodeWriter body)
        {
            HintName = hintName;
            Type = type;
            Body = body;
        }

        public string HintName { get; }

        /// <summary>The type whose file this is, or null for the context file.</summary>
        public TypeModel? Type { get; }

        public CodeWriter Body { get; }

        /// <summary>The body has passed its public surface; what follows is written oblivious.</summary>
        public bool PrivateRegion { get; set; }
    }

    private List<GeneratedFile> EmitFiles()
    {
        // Roslyn compares hint names case-insensitively, so two types differing only by case share a stem.
        var hintNames = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var contextFile = Open($"{_model.HintNamePrefix}.g.cs", null, 4096 + _types.Length * 256);
        hintNames.Add(contextFile.HintName);

        var typeFiles = new OpenFile[_types.Length];
        foreach (var type in _types)
        {
            _cancellationToken.ThrowIfCancellationRequested();
            var stem = $"{_model.HintNamePrefix}.{type.ShortName}";
            var hintName = $"{stem}.g.cs";
            for (var n = 2; !hintNames.Add(hintName); n++)
                hintName = $"{stem}_{n}.g.cs";

            var file = typeFiles[type.Id] = Open(hintName, type, 2048);
            _w = file.Body;
            _oblivious = false;
            EmitKinds(type);
            EmitConvenienceProperty(type);
            if (type.EmitWrapper)
                EmitWrapper(type);

            // The private region starts here; a type with no private code leaves no directive behind.
            var beforePrivate = file.Body.Length;
            EnterPrivate(file);
            var afterDirective = file.Body.Length;
            EmitCores(type);
            EmitDispatchHolders();
            if (file.Body.Length == afterDirective)
            {
                file.Body.Truncate(beforePrivate);
                file.PrivateRegion = false;
            }
        }

        // Span cores are requested by the containers emitted above and belong to the element they compare.
        foreach (var element in _spanCores.OrderBy(i => i))
        {
            _w = typeFiles[element].Body;
            EnterPrivate(typeFiles[element]);
            EmitSpanCores(Type(element));
        }

        _w = contextFile.Body;
        EnterPrivate(contextFile);
        EmitConstants();
        EmitBlockGuards();
        EmitLookup();
        EmitAccessors();
        EmitAccessorHolders();
        EmitCustomComparerHolders();

        var files = new List<GeneratedFile>(_types.Length + 1) { Close(contextFile)! };
        foreach (var file in typeFiles)
        {
            if (Close(file) is { } generated)
                files.Add(generated);
        }

        return files;
    }

    /// <summary>A namespace written <c>namespace X;</c>, from C# 10: every line of the file is one level less indented.</summary>
    private bool FileScopedNamespace => _model.Namespace.Length > 0 && _model.Capabilities.FileScopedNamespace;

    /// <summary>The blocks around a class body: a block namespace, containing types and the context class itself.</summary>
    private int SkeletonDepth => (_model.Namespace.Length > 0 && !FileScopedNamespace ? 1 : 0) + _model.ContainingTypes.Count + 1;

    /// <summary>A body writer for a file, positioned at the class body's indentation.</summary>
    private OpenFile Open(string hintName, TypeModel? type, int capacity) =>
        new(hintName, type, new CodeWriter(capacity, SkeletonDepth));

    /// <summary>
    /// Wraps a body that received something in its header and skeleton and returns the file; null for an empty body.
    /// The context file is always emitted, since the lookup lives there.
    /// </summary>
    private GeneratedFile? Close(OpenFile file)
    {
        if (file.Body.Length == 0 && file.Type is not null)
            return null;

        var body = file.Body.ToString();
        _w = new CodeWriter(body.Length + 4096);
        var values = _headerValues ??= HeaderValues();
        if (file.Type is { IsUnsafe: true } unsafeType)
            values = new Dictionary<string, string>(values, StringComparer.Ordinal) { ["FileNotice"] = TrimmingNotice(unsafeType) };

        EmitHeader(values, contextFile: file.Type is null);
        if (!_w.EndsWithBlankLine)
            _w.Line();

        if (FileScopedNamespace)
        {
            _w.Line($"namespace {_model.Namespace};");
            _w.Line();
        }
        else if (_model.Namespace.Length > 0)
        {
            _w.Open($"namespace {_model.Namespace}");
        }

        EmitAliases(body);

        foreach (var containing in _model.ContainingTypes)
            _w.Open($"partial {containing}");

        _w.Open($"{_model.Accessibility} partial class {Analysis.Naming.TypeIdentifier(_model.Name)}");
        _w.AppendRaw(body);
        for (var i = 0; i < SkeletonDepth; i++)
            _w.Close();

        return new GeneratedFile(file.HintName, _w.ToString());
    }

    /// <summary>
    /// A short alias for each framework class the body names, so a call reads <c>DeqHelpers.FloatBits(x)</c> rather
    /// than repeating the class's global:: name at every use. They sit inside the namespace declaration: an alias
    /// there shadows a type of the same name in an enclosing namespace and a <c>global using</c> alias, and clashes
    /// only with a type of that name declared in the context's own namespace. The body is complete when this runs, so
    /// only the aliases it uses are declared; an alias matched in a user type's name costs one unused line.
    /// </summary>
    private void EmitAliases(string body)
    {
        var any = false;
        foreach (var (alias, target) in KnownTypes.FrameworkAliases)
        {
            if (body.IndexOf(alias, StringComparison.Ordinal) < 0)
                continue;

            _w.Line($"using {alias} = {target};");
            any = true;
        }

        if (any)
            _w.Line();
    }

    private void EmitConstants()
    {
        _w.Line($"private const int MaxComparisonPairs = {_model.Options.MaxComparisonPairs};");
        _w.Line($"private const int MaxUnorderedCollisionRun = {_model.Options.MaxUnorderedCollisionRun};");
        if (IsTree)
            _w.Line($"private const int MaxDepth = {_model.Options.MaxDepth};");

        _w.Line();
    }

    /// <summary>The cycle-guard kinds of a type, read only by its own cores.</summary>
    private void EmitKinds(TypeModel type)
    {
        if (!type.IsGuarded && !type.BoxedAdapterGuarded)
            return;

        if (type.IsGuarded)
            _w.Line($"private const int Kind_{type.ShortName} = {type.GuardKind};");

        if (type.BoxedAdapterGuarded)
            _w.Line($"private const int Kind_Boxed_{type.ShortName} = {type.BoxedGuardKind};");

        _w.Line();
    }

    private void EmitLookup()
    {
        var mapped = _types.Where(t => t.EmitWrapper).ToList();
        using (_w.Block("private static class ComparerMap"))
        {
            _w.Line("static ComparerMap() { }");
            _w.Line($"internal static readonly global::System.Collections.Generic.Dictionary<{KnownTypes.GlobalType}, object> Value = Build();");
            using (_w.Member($"private static global::System.Collections.Generic.Dictionary<{KnownTypes.GlobalType}, object> Build()"))
            {
                _w.Line($"global::System.Collections.Generic.Dictionary<{KnownTypes.GlobalType}, object> map = new global::System.Collections.Generic.Dictionary<{KnownTypes.GlobalType}, object>({mapped.Count});");
                foreach (var type in mapped)
                    _w.Line($"map.Add(typeof({type.GlobalName}), {type.ShortName}EqualityComparer.Instance);");

                _w.Return("map");
            }
        }
        _w.Line();
                using (_w.Block("private static class Cache<T>"))
            _w.Line($"internal static readonly {KnownTypes.GlobalIEqualityComparer}<T>{Q()} Value = LookupEqualityComparer<T>(ComparerMap.Value);");
        _w.Line();
        // The public lookup keeps its annotations, inside the context file's private region.
        if (Annotations)
            _w.Line("#nullable enable annotations");

        _oblivious = false;
        _w.Line("/// <summary>");
        _w.Line("/// The deep, by-value comparer for <typeparamref name=\"T\"/>. Throws");
        _w.Line($"/// <see cref=\"{KnownTypes.GlobalFramework}.DeepEqualsMissingComparerException\"/> when <typeparamref name=\"T\"/> has no comparer in this context.");
        _w.Line("/// </summary>");
        EmitUnsafeAttributes(_model.HasUnsafeTypes);
        _w.Arrow(
            $"public static {KnownTypes.GlobalIEqualityComparer}<T> GetEqualityComparer<T>()", 
            "RequireEqualityComparer<T>(Cache<T>.Value)");
        _oblivious = true;
        if (Annotations)
            _w.Line(ObliviousDirective);

        _w.Line();
    }

    private void EmitConvenienceProperty(TypeModel type)
    {
        if (!type.EmitConvenienceProperty)
            return;

        _w.Line($"/// <summary>The deep, by-value comparer for <c>{DocName(type)}</c>.</summary>");
        if (type.ObsoleteAttribute is { } obsolete)
            _w.Line(obsolete);

        if (type.IsUnsafe)
        {
            // The attributes belong on the getter: RequiresUnreferencedCode targets methods, not properties.
            using (_w.Block($"{type.Accessibility} static {type.ShortName}EqualityComparer {Identifier(type.ShortName)}"))
            {
                EmitUnsafeAttributes(true);
                _w.Arrow("get", $"{type.ShortName}EqualityComparer.Instance");
            }
        }
        else
        {
            _w.Arrow(
                $"{type.Accessibility} static {type.ShortName}EqualityComparer {Identifier(type.ShortName)}",
                $"{type.ShortName}EqualityComparer.Instance");
        }

        _w.Line();
    }

    private void EmitUnsafeAttributes(bool unsafeType)
    {
        if (!unsafeType) 
            return;

        if (_model.Capabilities.HasRequiresUnreferencedCode)
            _w.Line("[global::System.Diagnostics.CodeAnalysis.RequiresUnreferencedCode(\"This comparer reads private fields through reflection-built delegates; trimming can remove them.\")]");

        if (_model.Capabilities.HasRequiresDynamicCode) 
            _w.Line("[global::System.Diagnostics.CodeAnalysis.RequiresDynamicCode(\"This comparer compiles expression trees for private field access.\")]");
    }

    private void EmitSuppressions(TypeModel type)
    {
        if (!_model.Capabilities.HasUnconditionalSuppressMessage || 
            type.Members.All(m => m.Access != MemberAccess.Delegate)) 
            return;

        _w.Line("[global::System.Diagnostics.CodeAnalysis.UnconditionalSuppressMessage(\"Trimming\", \"IL2026\", Justification = \"The warning is surfaced on the context's convenience property and GetEqualityComparer<T>().\")]");
        _w.Line("[global::System.Diagnostics.CodeAnalysis.UnconditionalSuppressMessage(\"AOT\", \"IL3050\", Justification = \"The warning is surfaced on the context's convenience property and GetEqualityComparer<T>().\")]");
    }

    /// <summary>Suppressions for a method, then the method itself: the attributes and what they decorate are one unit.</summary>
    private IDisposable Method(TypeModel type, string signature)
    {
        EmitSuppressions(type);
        return _w.Member(signature);
    }

    /// <summary>Same reference is equal and one null is not; every reference-type Equals_ starts here.</summary>
    private void EmitReferencePrelude()
    {
        _w.Line($"if ({RefEq("x", "y")}) return true;");
        _w.Line("if (x is null || y is null) return false;");
    }

    /// <summary>
    /// The cycle guard, for the types that need one: a pair already being compared is taken as equal, which is what
    /// bounds the recursion. The boxed adapter has its own kind, and its own reason to be guarded.
    /// </summary>
    private IDisposable GuardScope(TypeModel type, bool boxed = false)
    {
        if (!(boxed ? type.BoxedAdapterGuarded : type.IsGuarded))
            return NoScope.Instance;

        if (IsTree)
        {
            EmitDepthGuard(type);
            return NoScope.Instance;
        }

        if (!_model.Options.IsPath)
        {
            EmitTryEnter(type, boxed);
            return NoScope.Instance;
        }

        // Path: the pair is an ancestor only while this core runs, so it leaves the state on every return.
        _w.Line("int pathMark = state.Mark();");
        EmitTryEnter(type, boxed);
        var body = _w.Block("try");
        return new ActionScope(() =>
        {
            body.Dispose();
            using (_w.Block("finally"))
                _w.Line("state.Rollback(pathMark);");
        });
    }

    /// <summary>
    /// One step of Brent's cycle detection over the chain in <paramref name="cursor"/>, run once per node after the node is
    /// compared or hashed: meeting the saved node again means a cycle; the saved node moves to the cursor whenever the
    /// step count reaches the next power of two, so a cycle of length L after a prefix of P is found within about 2(P + L)
    /// steps.
    /// </summary>
    private void EmitBrentStep(TypeModel type, string cursor)
    {
        _w.Line($"if ({RefEq(cursor, "tortoise")}) {KnownTypes.DeqHelpers}.ThrowCycle(typeof({type.GlobalName}));");
        using (_w.Block("if (lambda++ == power)"))
        {
            _w.Line($"tortoise = {cursor};");
            _w.Line("power <<= 1;");
            _w.Line("lambda = 1;");
        }
    }

    private void EmitTryEnter(TypeModel type, bool boxed = false) =>
        _w.Line($"if (!state.TryEnter(Kind_{(boxed ? "Boxed_" : string.Empty)}{type.ShortName}, x, y)) return true;");

    /// <summary>
    /// Under Path, a tail loop is the chain of its ancestors: every node's pair stays entered while the loop walks on,
    /// exactly as nested calls would keep them, and all of them leave together when the loop ends, however it ends.
    /// </summary>
    private IDisposable TailLoopScope(TypeModel type)
    {
        if (!type.IsGuarded || !_model.Options.IsPath)
            return NoScope.Instance;

        _w.Line("int pathMark = state.Mark();");
        var body = _w.Block("try");
        return new ActionScope(() =>
        {
            body.Dispose();
            using (_w.Block("finally"))
                _w.Line("state.Rollback(pathMark);");
        });
    }

    private sealed class NoScope : IDisposable
    {
        public static readonly NoScope Instance = new();

        public void Dispose()
        {
        }
    }

    private sealed class ActionScope(Action dispose) : IDisposable
    {
        public void Dispose() => dispose();
    }

    // ----- helpers -----------------------------------------------------------------------------------------------------

    /// <summary>Returns the nullable annotation symbol if it is availble, otherwise empty string.</summary>
    private string Q() => Annotations && !_oblivious ? "?" : string.Empty;

    /// <summary>
    /// Writing the private implementation: its declarations are nullability-oblivious, so no <c>?</c> is written. One
    /// core serves every nullability spelling of a type, since <c>List&lt;string&gt;</c> and <c>List&lt;string?&gt;</c> are
    /// one runtime type, and C# checks the nested nullability of a generic or tuple argument at every call (CS8620); an
    /// oblivious parameter accepts every spelling. Bodies keep full flow analysis.
    /// </summary>
    private bool _oblivious;

    private const string ObliviousDirective = "#nullable disable annotations";

    /// <summary>Starts the private region of a file once: its declarations are oblivious from here on.</summary>
    private void EnterPrivate(OpenFile file)
    {
        _oblivious = true;
        if (file.PrivateRegion || !Annotations)
            return;

        file.Body.Line(ObliviousDirective);
        file.PrivateRegion = true;
    }

    private string Param(TypeModel type) => type.IsValueType ? type.GlobalName : type.GlobalName + Q();

    /// <summary>
    /// Returns csharp-safe identifier for a name (@ prefixed if it is a keyword).
    /// </summary>
    private static string Identifier(string name) => Analysis.Naming.Identifier(name);

    private bool IsTree => _model.Options.IsTree;

    /// <summary>
    /// The comparison state a core that reaches a cycle takes: the pair table under Graph and Path, the nesting depth
    /// under Tree. Everything the model records as needing state needs depth instead under Tree.
    /// </summary>
    private string StateParam(TypeModel type) => !type.NeedsState ? string.Empty : StateParamAlways;

    private string StateArg(TypeModel type) => !type.NeedsState ? string.Empty : StateArgAlways;

    /// <summary>The state parameter for a core that has one whatever its type says: a guarded boxed adapter, <c>EqualsExact_T</c>.</summary>
    private string StateParamAlways => IsTree ? ", int depth" : $", ref {KnownTypes.DeqState} state";

    private string StateArgAlways => IsTree ? ", depth" : ", ref state";

    /// <summary>Under Tree a hash core that reaches a cycle carries the depth too; under Graph and Path hashing needs no state.</summary>
    private string HashDepthParam(TypeModel type) => IsTree && type.NeedsState ? ", int depth" : string.Empty;

    private string HashDepthArg(TypeModel type) => IsTree && type.NeedsState ? ", depth" : string.Empty;

    /// <summary>
    /// The Tree guard in a hash core: the same guarded types as equality, since every cycle of the hash call graph passes
    /// through the same cores, so hashing a cycle the traversal enters throws where comparing it would.
    /// </summary>
    private void EmitHashGuard(TypeModel type)
    {
        if (IsTree && type.IsGuarded)
            EmitDepthGuard(type);
    }

    /// <summary>The Tree guard: one more level, a throw past MaxDepth, and a stack check, since MaxDepth bounds cycles, not the stack.</summary>
    private void EmitDepthGuard(TypeModel type)
    {
        _w.Line($"if (++depth > MaxDepth) {KnownTypes.DeqHelpers}.ThrowDepthExceeded(typeof({type.GlobalName.TrimEnd('?')}), MaxDepth);");
        _w.Line($"{KnownTypes.GlobalRuntimeHelpers}.EnsureSufficientExecutionStack();");
    }

    /// <summary>Call <see cref="object.ReferenceEquals"/></summary>
    private static string RefEq(string x, string y) => $"{KnownTypes.GlobalObject}.ReferenceEquals({x}, {y})";

    // ----- hash streams -------------------------------------------------------------------------------------------------

    /// <summary>A count as a hash: the shallow hash of a collection is its count, 1 when empty.</summary>
    private static string CountHash(string count) => $"({count} == 0 ? 1 : {count})";

    private string Combine<T>(IEnumerable<T> inputs, Func<T, string> selector) =>
        Combine(inputs.Select(selector).ToList());

    /// <summary>One <c>Combine</c> stream over the words, nested above the arity cap.</summary>
    private string Combine(List<string> words)
    {
        if (words.Count == 0)
            return "1";

        var inputs = words;
        while (inputs.Count > MaxCombineArity)
        {
            // One round of grouping: each group of at most MaxCombineArity inputs becomes a nested call.
            var nested = new List<string>(capacity: inputs.Count / MaxCombineArity + 1);
            for (var i = 0; i < inputs.Count; i += MaxCombineArity)
                nested.Add(ItemList($"{KnownTypes.DeqHashCode}.Combine(", inputs.GetRange(i, Math.Min(MaxCombineArity, inputs.Count - i)), ",", ")"));

            inputs = nested;
        }

        return ItemList($"{KnownTypes.DeqHashCode}.Combine(", inputs, ",", ")");
    }

    private void EmitPredicates<T>(IEnumerable<T> items, Func<T, string> selector, bool terminalReturnTrue) => 
        EmitPredicates(items.Select(selector).ToList(), terminalReturnTrue);
    
    /// <summary>
    /// Emits a predicate chain as chunks of at most MaxBinaryExpressionArity,
    /// returning false on the first failed chunk.
    /// </summary>
    private void EmitPredicates(List<string> predicates, bool terminalReturnTrue)
    {
        var arity = _model.Options.MaxBinaryExpressionArity;
        if (predicates.Count == 0)
        {
            if (terminalReturnTrue)
                _w.Return("true");

            return;
        }

        if (predicates.Count <= arity && terminalReturnTrue)
        {
            // Several predicates start on the line after "return" (or after the arrow), since a single one is the only
            // case that fits beside it.
            _w.Return(ItemList(string.Empty, predicates, " &&", string.Empty));
            return;
        }

        for (var i = 0; i < predicates.Count; i += arity)
        {
            var chunk = predicates.GetRange(i, Math.Min(arity, predicates.Count - i));
            _w.Line(ItemList("if (!(", chunk, " &&", ")) return false;"));
        }

        if (terminalReturnTrue)
            _w.Return("true");
    }

    // ----- member reads ---------------------------------------------------------------------------------------------------

    /// <summary>
    /// The expression that reads a member from a receiver of the declaring type;
    /// <paramref name="inReceiver"/> when the receiver is an in parameter.
    /// </summary>
    private static string Read(MemberModel member, string receiver, bool inReceiver)
    {
        switch (member.Access)
        {
                        case MemberAccess.Direct:
                return $"{receiver}.{Identifier(member.FieldMetadataName)}";

            case MemberAccess.Getter:
                return $"{receiver}.{Identifier(member.Name)}";

            
            case MemberAccess.UnsafeAccessor:
                var accessor = member.GenericAccessor 
                    ? $"{member.GenericHolderName}{member.GenericTypeArguments}.{member.AccessorName}"
                    : member.AccessorName;
                return member.DeclaringTypeIsValueType
                    ? $"{accessor}(ref {WritableReceiver(receiver, inReceiver)})"
                    : $"{accessor}({receiver})";

            case MemberAccess.Delegate:
            default:
                return member.DeclaringTypeIsValueType
                    ? $"{member.DeclaringTypeShortName}_Accessors.{member.AccessorName}(ref {WritableReceiver(receiver, inReceiver)})"
                    : $"{member.DeclaringTypeShortName}_Accessors.{member.AccessorName}({receiver})";
        }
    }

    /// <summary>
    /// The payload of a nullable whose <c>HasValue</c> has already been checked. A struct or decimal payload is reached by
    /// reference through the runtime's <c>Nullable.GetValueRefOrDefaultRef</c> where it exists (.NET 7 and later), so a
    /// nullable read in place is also compared in place; everything else is the copy <c>GetValueOrDefault()</c> returns.
    /// No <c>in</c> at the call site: a getter's value then binds through a temporary, and the header suppresses the
    /// warnings the <c>ref readonly</c> parameter raises for either argument.
    /// </summary>
    private string NullablePayload(TypeModel payload, string nullable, bool reference) =>
        _model.Capabilities.HasNullableGetValueRefOrDefaultRef && (reference || IsIdentifier(nullable)) &&
        (payload.Kind == TypeKind.Struct || payload.LeafRule == LeafRule.Decimal)
            ? $"global::System.Nullable.GetValueRefOrDefaultRef(in {nullable})"
            : $"{nullable}.GetValueOrDefault()";

    /// <summary>A parameter or local: a variable that <c>in</c> can pass by reference.</summary>
    private static bool IsIdentifier(string expression) =>
        expression.Length > 0 && (char.IsLetter(expression[0]) || expression[0] == '_') && expression.All(c => char.IsLetterOrDigit(c) || c == '_');

    private static string WritableReceiver(string receiver, bool inReceiver) =>
        inReceiver ? $"global::System.Runtime.CompilerServices.Unsafe.AsRef(in {receiver})" : receiver;

    // ----- equality expressions ---------------------------------------------------------------------------------------------

    /// <summary>A boolean expression comparing two values of <paramref name="type"/>; state is passed when the type needs it.</summary>
    /// <param name="references">
    /// The operands are variables, a field read directly or through an accessor, so a nullable's payload can be reached
    /// by reference; a getter's result is a value and is copied instead.
    /// </param>
    private string Eq(TypeModel type, string x, string y, bool references = false)
    {
        switch (type.Kind)
        {
            case TypeKind.Leaf:
                return LeafEq(type, x, y);
            
            case TypeKind.Nullable:
                var payload = Type(type.PayloadTypeId);
                return $"({x}.HasValue == {y}.HasValue && (!{x}.HasValue || {Eq(payload, NullablePayload(payload, x, references), NullablePayload(payload, y, references))}))";
            
            case TypeKind.Struct:
                if (type.InlineAsSmallStruct)
                {
                    var predicates = type.Members.Select(m => Eq(Type(m.TypeId), Read(m, x, false), Read(m, y, false))).ToList();
                    return predicates.Count == 0 ? "true" : ItemList("(", predicates, " &&", ")");
                }

                // An `in` parameter binds by reference without the keyword at the call site; writing `in` would require a
                // variable, and arguments such as `e.Value` or `GetValueOrDefault()` are not (CS8156).
                return $"Equals_{type.ShortName}({x}, {y}{StateArg(type)})";
            
            default:
                return $"Equals_{type.ShortName}({x}, {y}{StateArg(type)})";
        }
    }

    private string LeafEq(TypeModel type, string x, string y)
    {
        switch (type.LeafRule)
        {
            case LeafRule.Primitive:
            case LeafRule.WideInteger:
            case LeafRule.Guid:
                return $"{x} == {y}";
            
            case LeafRule.Enum:
                return $"({type.EnumUnderlyingGlobalName}){x} == ({type.EnumUnderlyingGlobalName}){y}";
            
                        case LeafRule.String:
                return $"{x} == {y}";
            
            case LeafRule.Single:
                return $"{FloatBits(x)} == {FloatBits(y)}";

            case LeafRule.Double:
                return $"{DoubleBits(x)} == {DoubleBits(y)}";

            case LeafRule.Half:
                return $"{HalfBits(x)} == {HalfBits(y)}";
            
                        case LeafRule.Decimal:
                return $"{KnownTypes.DeqHelpers}.DecimalEquals({x}, {y})";
            
            case LeafRule.DateTime:
                return $"{KnownTypes.DeqHelpers}.DateTimeBits({x}) == {KnownTypes.DeqHelpers}.DateTimeBits({y})";
            
            case LeafRule.DateTimeOffset:
                return $"({x}.Ticks == {y}.Ticks && {x}.Offset == {y}.Offset)";
            
            case LeafRule.FloatAggregate:
                // Matrix4x4 is sixteen of these; a component is as much a member as a property is.
                return ItemList("(", type.AggregateComponents.Select(c => c.IsDouble
                    ? $"{DoubleBits($"{x}.{c.Expression}")} == {DoubleBits($"{y}.{c.Expression}")}"
                    : $"{FloatBits($"{x}.{c.Expression}")} == {FloatBits($"{y}.{c.Expression}")}").ToList(), " &&", ")");
            
            case LeafRule.Uri:
                return RefLeaf(x, y, 
                    $"(string.Equals({x}.OriginalString, {y}.OriginalString, {KnownTypes.GlobalStringComparison}.Ordinal) && {x}.IsAbsoluteUri == {y}.IsAbsoluteUri)");
            
            case LeafRule.Regex:
                return RefEq(x, y);
            
            case LeafRule.Custom:
                return CustomEq(type, x, y);
            
            case LeafRule.UserSimple:
            case LeafRule.Default:
            default:
                return type.IsValueType ? DefaultEq(type, x, y) : RefLeaf(x, y, DefaultEq(type, x, y));
        }
    }

    /// <summary>
    /// The default-equality rule for two non-null operands of the exact static type.
    /// A type implementing <c>IEquatable{Self}</c> is called directly:
    /// <c>x.Equals(y)</c> when that implementation is a public method on a struct or sealed class, otherwise through the constrained framework shim.
    /// Everything else, including a derived type that only inherits <c>IEquatable{Base}</c>, keeps <c>EqualityComparer{T}.Default</c>.
    /// Both direct forms are what the default comparer does for such a type after its null checks.
    /// </summary>
    private static string DefaultEq(TypeModel type, string x, string y)
    {
        if (!type.ImplementsIEquatable) 
            return $"{KnownTypes.GlobalEqualityComparer}<{type.GlobalName}>.Default.Equals({x}, {y})";

        return type is { HasPublicEquatableEquals: true, IsSealed: true }
            ? $"({x}).Equals({y})"
            : $"{KnownTypes.DeqHelpers}.EquatableEquals<{type.GlobalName}>({x}, {y})";
    }

    private static string RefLeaf(string x, string y, string rule) => 
        $"({RefEq(x, y)} || (!({x} is null) && !({y} is null) && {rule}))";

    // ----- bit blocks -----------------------------------------------------------------------------------------------------
    //
    // A sequence of bit-block elements is one block of bytes: it compares with the runtime's vectorized memory compare
    // and hashes with seeded XxHash3. The hash of such a sequence is defined that way for every container shape of its
    // declared type, so every path of a core that hashes one goes through the block helpers. A bit-block struct is one
    // only when the runtime lays it out without padding, which a flag computed once per process confirms; the flag is a
    // constant for the process, so the paths it selects never mix.

    /// <summary>True when sequences of <paramref name="element"/> take the byte paths.</summary>
    private bool BlockElement(TypeModel element) => _model.Capabilities.BitBlocks && element.IsBitBlock;

    /// <summary>The flag a struct's byte paths depend on, or null for a leaf, which needs none.</summary>
    private string? BlockGuard(TypeModel element)
    {
        if (element.BitBlockChecks.Count == 0)
            return null;

        _blockGuards.Add(element.Id);
        return $"{element.ShortName}_IsBitBlock";
    }

    /// <summary>
    /// Emits <paramref name="body"/>, the byte path of a hash or comparison, ahead of the per-element path. Returns true
    /// when the byte path is unconditional and nothing after it may be emitted; a struct's path runs under its flag and
    /// falls through to the per-element path when the flag is false.
    /// </summary>
    private bool EmitBlockPath(TypeModel element, Action body)
    {
        var guard = BlockGuard(element);
        if (guard is null)
        {
            body();
            return true;
        }

        using (_w.Block($"if ({guard})"))
            body();

        return false;
    }

    /// <summary>One flag per bit-block struct some path reads: the runtime size of it and of every struct nested in it.</summary>
    private void EmitBlockGuards()
    {
        foreach (var id in _blockGuards)
        {
            var type = Type(id);
            var checks = type.BitBlockChecks.Select(c => $"{KnownTypes.DeqBlocks}.HasSize<{c.GlobalName}>({c.Size})");
            _w.Line($"private static readonly bool {type.ShortName}_IsBitBlock = {string.Join(" && ", checks)};");
        }

        if (_blockGuards.Count > 0)
            _w.Line();
    }

    /// <summary>The block-hash helper call over <paramref name="argument"/>: <c>HashBlock</c>, <c>HashReadOnlyList</c>, <c>HashList</c> or <c>HashEnumerable</c>.</summary>
    private string BlockHash(string helper, TypeModel element, string argument) =>
        $"{KnownTypes.DeqBlocks}.{helper}<{element.GlobalName}>({argument})";

    /// <summary>
    /// The byte path of an interface-typed sequence's hash: an immutable array through its span, anything else through
    /// the helper for its interface, which takes an array's or a list's span itself and copies everything else.
    /// </summary>
    private void EmitInterfaceBlockHash(TypeModel type, TypeModel element, string iface)
    {
        if (_model.Capabilities.HasImmutableArray)
        {
            var immutable = $"global::System.Collections.Immutable.ImmutableArray<{element.GlobalName}>";
            // Named apart from the per-element path's local, which a struct's guarded byte path sits in front of.
            _w.Line(ImmutableSpans
                ? $"if (o is {immutable} ib) return ib.IsDefault ? 0 : {BlockHash("HashBlock", element, "ib.AsSpan()")};"
                : $"if (o is {immutable} ib && ib.IsDefault) return 0;");
        }

        var generic = "global::System.Collections.Generic.";
        if (iface.StartsWith($"{generic}IReadOnlyList<", StringComparison.Ordinal))
            _w.Return(BlockHash("HashReadOnlyList", element, $"({iface})o"));
        else if (iface.StartsWith($"{generic}IList<", StringComparison.Ordinal))
            _w.Return(BlockHash("HashList", element, $"({iface})o"));
        else
            _w.Return(BlockHash("HashEnumerable", element, $"({generic}IEnumerable<{element.GlobalName}>)o"));
    }

    // The storage bits of a floating-point value, through the framework shims that pick the fastest reinterpretation
    // each asset has. Never a numeric conversion: NaN payloads and the sign of zero stay distinct.

    private static string FloatBits(string value) => $"{KnownTypes.DeqHelpers}.FloatBits({value})";

    private static string DoubleBits(string value) => $"{KnownTypes.DeqHelpers}.DoubleBits({value})";

    private static string HalfBits(string value) => $"global::System.BitConverter.HalfToUInt16Bits({value})";

    /// <summary>The four bytes of a float as a narrow hash word.</summary>
    private static string FloatWord(string value) => $"unchecked((int){FloatBits(value)})";

    private string CustomEq(TypeModel type, string x, string y)
    {
        var custom = _model.CustomComparers[type.CustomComparerIndex];
        if (type.CustomWrapsNullable)
            return $"{custom.HolderName}.Value.Equals((global::System.Nullable<{type.GlobalName}>){x}, (global::System.Nullable<{type.GlobalName}>){y})";

        var call = $"{custom.HolderName}.Value.Equals({x}, {y})";
        if (custom.HandleNulls || (type.IsValueType && !IsNullableName(type))) 
            return call;

        return type.IsValueType 
            ? $"({x}.HasValue == {y}.HasValue && (!{x}.HasValue || {call}))" 
            : RefLeaf(x, y, call);
    }

    private static bool IsNullableName(TypeModel type) => type.GlobalName.EndsWith("?", StringComparison.Ordinal);

    // ----- hash expressions ------------------------------------------------------------------------------------------------

    /// <summary>The hash of a value reached through an edge; null means the edge is omitted at this level.</summary>
    private string? HashOrOmit(TypeModel type, string value, int level, bool sameScc, bool reference = false)
    {
        switch (type.Kind)
        {
            case TypeKind.Leaf:
                return LeafHash(type, value);

            case TypeKind.Nullable:
                var payload = HashOrOmit(Type(type.PayloadTypeId), NullablePayload(Type(type.PayloadTypeId), value, reference), level, sameScc);
                return payload is { } p ? $"({value}.HasValue ? {p} : 0)" : null;

            case TypeKind.Struct:
                if (type.InlineAsSmallStruct)
                    return Combine(type.Members,
                        m => LeafHash(Type(m.TypeId), Read(m, value, false)));

                break;
        }

        // An edge that leaves the component calls the full hash. Inside it, a structural edge keeps the caller's level
        // and a payload edge steps one level down, and is left out entirely at level 0.
        if (!sameScc)
            return $"{HashName(type, 1)}({value}{HashDepthArg(type)})";

        if (IsContainerOrProduct(type))
            return $"{HashName(type, level)}({value}{HashDepthArg(type)})";

        return level == 0 ? null : $"{HashName(type, level - 1)}({value}{HashDepthArg(type)})";
    }

    /// <summary>
    /// The hash core of <paramref name="type"/> at <paramref name="level"/>: <c>GetHashCode_T</c> at level 1, the public
    /// one; <c>ShallowHashCode_T</c> at level 0; <c>MatchHashCode_T_L{n}</c> for the deeper levels the matching
    /// fingerprint uses. A type without levels has only the first.
    /// </summary>
    private static string HashName(TypeModel type, int level) =>
        !type.HasShallowHash || level == 1 ? $"GetHashCode_{type.ShortName}"
        : level == 0 ? $"ShallowHashCode_{type.ShortName}"
        : $"MatchHashCode_{type.ShortName}_L{level}";

    /// <summary>The members-only hash of a class at <paramref name="level"/>, which dispatch calls after it has tested the runtime type.</summary>
    private static string MembersHashName(TypeModel type, int level) =>
        level == 1 ? $"HashMembers_{type.ShortName}"
        : level == 0 ? $"ShallowHashMembers_{type.ShortName}"
        : $"MatchHashMembers_{type.ShortName}_L{level}";

    /// <summary>The levels a type's hash cores exist at: 1, then 0 for a cyclic type, then 2..k where the fingerprint reaches.</summary>
    private static IEnumerable<int> HashLevels(TypeModel type)
    {
        yield return 1;
        if (!type.HasShallowHash)
            yield break;

        yield return 0;
        for (var level = 2; level <= type.MatchHashLevels; level++)
            yield return level;
    }

    /// <summary>The levels above 1 a type's hash cores exist at, for the containers whose deeper cores are a plain walk.</summary>
    private static IEnumerable<int> MatchLevels(TypeModel type) => HashLevels(type).Where(l => l > 1);

    /// <summary>
    /// The fingerprint of one set element, dictionary key or dictionary value for unordered matching: the level-k hash,
    /// which follows payload edges k deep into a cycle where the public hash follows one. An acyclic type's full hash
    /// already sees everything.
    /// </summary>
    private string FingerprintWord(TypeModel type, string value)
    {
        if (type.Kind == TypeKind.Nullable)
        {
            var payload = FingerprintWord(Type(type.PayloadTypeId), $"{value}.GetValueOrDefault()");
            return $"({value}.HasValue ? {payload} : 0)";
        }

        if (type.HasShallowHash && type.MatchHashLevels > 1)
            return $"{HashName(type, type.MatchHashLevels)}({value}{HashDepthArg(type)})";

        return HashOrOmit(type, value, 1, sameScc: false) ?? "0";
    }

    /// <summary>The hash of a value reached through an edge as a word of the stream's type; <c>0</c> when the edge is omitted.</summary>
    private string HashWordExpr(TypeModel type, string value, int level, bool sameScc) =>
        HashOrOmit(type, value, level, sameScc) ?? "0";

    /// <summary>
    /// The words a member contributes to its owner's hash stream, in statement context. A leaf wider than a word is
    /// read once into a local named <paramref name="local"/> and split into its words, so the owner mixes them into one
    /// seeded stream instead of finishing a nested hash per member; an inlined struct contributes its members' words.
    /// Everything else contributes the single word of its own hash, or nothing when the level omits it.
    /// </summary>
    private void HashWords(TypeModel type, string value, int level, bool sameScc, string local, List<string> words, bool reference = false)
    {
        switch (type.Kind)
        {
            case TypeKind.Leaf when WideLeafWords(type, value, local, words):
                return;

            case TypeKind.Struct when type.InlineAsSmallStruct:
                var k = 0;
                foreach (var member in type.Members)
                    HashWords(Type(member.TypeId), Read(member, value, false), level, sameScc, $"{local}_{k++}", words);

                return;
        }

        var single = HashOrOmit(type, value, level, sameScc, reference);
        if (single is { } word)
            words.Add(word);
    }

    /// <summary>
    /// Reads a wide leaf into <paramref name="local"/> and appends its 32-bit words: always the storage bits and never a
    /// numeric conversion. False when the leaf is not wide.
    /// </summary>
    private bool WideLeafWords(TypeModel type, string value, string local, List<string> words)
    {
        switch (type.LeafRule)
        {
            case LeafRule.WideInteger:
                if (type.GlobalName.EndsWith("Int128", StringComparison.Ordinal))
                    return false;   // keeps its own seeded hash

                var unsigned = type.GlobalName is "ulong" or "nuint" || type.GlobalName.EndsWith("UIntPtr", StringComparison.Ordinal);
                Bits64(local, unsigned ? $"(ulong){value}" : $"unchecked((ulong)(long){value})", words);
                return true;

            case LeafRule.Enum:
                if (type.EnumUnderlyingWidth != 8)
                    return false;

                Bits64(local, type.EnumUnderlyingUnsigned ? $"(ulong){value}" : $"unchecked((ulong)(long){value})", words);
                return true;

            case LeafRule.Double:
                Bits64(local, DoubleBits(value), words);
                return true;

            case LeafRule.DateTime:
                Bits64(local, $"{KnownTypes.DeqHelpers}.DateTimeBits({value})", words);
                return true;

            case LeafRule.DateTimeOffset:
                _w.Line($"global::System.DateTimeOffset {local} = {value};");
                Bits64($"{local}t", $"unchecked((ulong){local}.Ticks)", words);
                Bits64($"{local}o", $"unchecked((ulong){local}.Offset.Ticks)", words);
                return true;

            case LeafRule.Guid:
                _w.Line($"global::System.Guid {local} = {value};");
                Bits128(local, "Guid", words);
                return true;

            case LeafRule.Decimal:
                _w.Line($"decimal {local} = {value};");
                Bits128(local, "Decimal", words);
                return true;

            case LeafRule.FloatAggregate:
                _w.Line($"{type.GlobalName} {local} = {value};");
                var k = 0;
                foreach (var component in type.AggregateComponents)
                {
                    if (component.IsDouble)
                        Bits64($"{local}_{k}", DoubleBits($"{local}.{component.Expression}"), words);
                    else
                        words.Add(FloatWord($"{local}.{component.Expression}"));

                    k++;
                }

                return true;

            default:
                return false;
        }
    }

    /// <summary>Sixty-four bits of storage, given as a <c>ulong</c> expression: its two 32-bit halves, read from a local.</summary>
    private void Bits64(string local, string bits, List<string> words)
    {
        _w.Line($"ulong {local} = {bits};");
        words.Add($"unchecked((int){local})");
        words.Add($"unchecked((int)({local} >> 32))");
    }

    /// <summary>A 16-byte leaf already read into <paramref name="local"/>: its four 32-bit words, through the helper reader named <paramref name="prefix"/>.</summary>
    private void Bits128(string local, string prefix, List<string> words)
    {
        for (var i = 0; i < 4; i++)
            words.Add($"{KnownTypes.DeqHelpers}.{prefix}Word({local}, {i})");
    }

    private static bool IsContainerOrProduct(TypeModel type) => type.Kind is  
        TypeKind.Array or TypeKind.List or TypeKind.ImmutableArray or TypeKind.ArraySegment or TypeKind.Memory or 
        TypeKind.ListInterface or TypeKind.EnumerableInterface or TypeKind.Set or TypeKind.Dictionary or 
        TypeKind.KeyValuePair or TypeKind.ValueTuple or TypeKind.Tuple;

    /// <summary>The 32-bit hash of a leaf: the rule of the documented representation, never a numeric conversion.</summary>
    private string LeafHash(TypeModel type, string value)
    {
        switch (type.LeafRule)
        {
            case LeafRule.Primitive:
                return PrimitiveHash(type, value);
            case LeafRule.WideInteger:
                if (type.GlobalName.EndsWith("IntPtr", StringComparison.Ordinal))
                    return type.GlobalName.EndsWith("UIntPtr", StringComparison.Ordinal)
                        ? $"{KnownTypes.DeqHashCode}.Hash((ulong){value})"
                        : $"{KnownTypes.DeqHashCode}.Hash((long){value})";

                if (type.GlobalName.EndsWith("Int128", StringComparison.Ordinal) && !_model.Capabilities.HasFrameworkHash128)
                    // The resolved framework asset predates Int128: seed both 64-bit halves through the long overload.
                    return $"{KnownTypes.DeqHashCode}.Combine({KnownTypes.DeqHashCode}.Hash(unchecked((long){value})), {KnownTypes.DeqHashCode}.Hash(unchecked((long)({value} >> 64))))";

                return $"{KnownTypes.DeqHashCode}.Hash({value})";

            case LeafRule.Guid:
                return $"{KnownTypes.DeqHashCode}.Hash({value})";

            case LeafRule.Enum:
                return type.EnumUnderlyingWidth switch
                {
                    8 => type.EnumUnderlyingUnsigned ? $"{KnownTypes.DeqHashCode}.Hash((ulong){value})" : $"{KnownTypes.DeqHashCode}.Hash((long){value})",
                    4 => type.EnumUnderlyingUnsigned ? $"unchecked((int)(uint){value})" : $"(int){value}",
                    _ => $"(int)({type.EnumUnderlyingGlobalName}){value}",
                };

            case LeafRule.String:
                return $"{KnownTypes.DeqHashCode}.Hash({value})";

            case LeafRule.Single:
                return FloatWord(value);

            case LeafRule.Double:
                return $"{KnownTypes.DeqHashCode}.Hash({DoubleBits(value)})";

            case LeafRule.Half:
                return $"(int){HalfBits(value)}";

            case LeafRule.Decimal:
                return $"{KnownTypes.DeqHashCode}.Hash({value})";

            case LeafRule.DateTime:
                return $"{KnownTypes.DeqHashCode}.Hash({KnownTypes.DeqHelpers}.DateTimeBits({value}))";

            case LeafRule.DateTimeOffset:
                return $"{KnownTypes.DeqHashCode}.Combine({KnownTypes.DeqHashCode}.Hash({value}.Ticks), {KnownTypes.DeqHashCode}.Hash({value}.Offset.Ticks))";

            case LeafRule.FloatAggregate:
                return ItemList($"{KnownTypes.DeqHashCode}.Combine(", type.AggregateComponents.Select(c => c.IsDouble
                        ? $"{KnownTypes.DeqHashCode}.Hash({DoubleBits($"{value}.{c.Expression}")})"
                        : FloatWord($"{value}.{c.Expression}")).ToList(), ",", ")");

            case LeafRule.Uri:
                return $"({value} is null ? 0 : {KnownTypes.DeqHashCode}.Combine({KnownTypes.DeqHashCode}.Hash({value}.OriginalString), {value}.IsAbsoluteUri ? 1 : 0))";

            case LeafRule.Regex:
                return $"{KnownTypes.GlobalRuntimeHelpers}.GetHashCode({value})";

            case LeafRule.Custom:
                return CustomHash(type, value);

            case LeafRule.UserSimple:
            case LeafRule.Default:
            default:
                return type.IsValueType
                    ? $"{value}.GetHashCode()"
                    : $"({value} is null ? 0 : {value}.GetHashCode())";
        }
    }

    private static string PrimitiveHash(TypeModel type, string value) =>
        type.GlobalName switch
        {
            "int" => value,
            "uint" => $"unchecked((int){value})",
            "bool" => $"({value} ? 1 : 0)",
            _ => $"(int){value}"
        };

    private string CustomHash(TypeModel type, string value)
    {
        var custom = _model.CustomComparers[type.CustomComparerIndex];
        if (type.CustomWrapsNullable)
            return $"{custom.HolderName}.Value.GetHashCode((global::System.Nullable<{type.GlobalName}>){value})";

        var call = $"{custom.HolderName}.Value.GetHashCode({value})";
        if (custom.HandleNulls || (type.IsValueType && !IsNullableName(type))) 
            return call;

        return type.IsValueType 
            ? $"({value}.HasValue ? {call} : 0)" 
            : $"({value} is null ? 0 : {call})";
    }

    // ----- wrappers -----------------------------------------------------------------------------------------------------

    /// <summary>A type's name for an XML documentation comment: no <c>global::</c>, and markup characters escaped.</summary>
    private static string DocName(TypeModel type) =>
        Display(type.GlobalName).Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");

    private const string AggressiveInlining =
        "[global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]";

    private void EmitWrapper(TypeModel type)
    {
        var name = $"{type.ShortName}EqualityComparer";

        _w.Line($"/// <summary>Deep, by-value equality for <c>{DocName(type)}</c>.</summary>");
        // The comparer of an obsolete type is as obsolete as the type: a caller sees the same warning or error, and the
        // comparer's own members, an obsolete context, name the type without one.
        if (type.ObsoleteAttribute is { } obsolete)
            _w.Line(obsolete);

        _w.Line($"[global::System.CodeDom.Compiler.GeneratedCode(\"DeepEquals.SourceGenerator\", \"{GeneratorVersion}\")]");
        
        // A reference-type wrapper accepts null on both sides, so under nullable annotations it implements IEqualityComparer<T?>.
        using (_w.Block($"{type.Accessibility} sealed class {name} : {KnownTypes.GlobalIEqualityComparer}<{Param(type)}>"))
        {
            _w.Line("/// <summary>The comparer's single instance.</summary>");
            _w.Line($"public static readonly {name} Instance = new {name}();");
            _w.Line($"private {name}() {{ }}");
            _w.Line();
            
            // A struct is passed by value: unless the call inlines, the caller copies both operands to the stack and the
            // body reads them back, where a record's own Equals inlines and reads the fields in place. A stateful body
            // holds a try/finally the JIT does not inline, so only a stateless one asks.
            var inline = type.IsValueType && !type.NeedsState;

            // The comparer for object declares an instance Equals(object, object),
            // which hides the static one every class inherits from object; `new` states that this is meant.
            _w.Line("/// <inheritdoc/>");
            if (inline)
                _w.Line(AggressiveInlining);

            using (Method(type, $"public {(type.IsObject ? "new " : string.Empty)}bool Equals({Param(type)} x, {Param(type)} y)"))
                        {
                // Only a closure with a cycle can recurse without bound, and only its Equals: the hash stops one payload
                // edge into a cycle, and an acyclic closure is as deep as its declarations. Every cycle also passes
                // through a guard, whose TryEnter checks the stack again at each turn.
                var body = WrapperEqualsBody(type);
                if (type.NeedsState && IsTree)
                {
                    _w.Line($"{KnownTypes.GlobalRuntimeHelpers}.EnsureSufficientExecutionStack();");
                    _w.Line("int depth = 0;");
                    _w.Return(body);
                }
                else if (type.NeedsState)
                {
                    _w.Line($"{KnownTypes.GlobalRuntimeHelpers}.EnsureSufficientExecutionStack();");
                    _w.Line($"{KnownTypes.DeqState} state = new {KnownTypes.DeqState}(MaxComparisonPairs);");
                    using (_w.Block("try"))
                        _w.Return(body);
                    using (_w.Block("finally")) 
                        _w.Line("state.Dispose();");
                }
                else
                {
                    _w.Return(body);
                }
            }
            
            _w.Line();
            _w.Line("/// <inheritdoc/>");
            if (inline)
                _w.Line(AggressiveInlining);

            using (Method(type, $"public int GetHashCode({Param(type)} o)"))
            {
                // Under Tree a hash walks the whole value, bounded by the same depth as equality.
                if (type.NeedsState && IsTree)
                    _w.Line("int depth = 0;");

                _w.Return(WrapperHashBody(type));
            }
        }
        _w.Line();
    }

    private string WrapperEqualsBody(TypeModel type) => Eq(type, "x", "y");

    private string WrapperHashBody(TypeModel type)
    {
        var hash = HashOrOmit(type, "o", 1, sameScc: false);
        return hash ?? "1";
    }

