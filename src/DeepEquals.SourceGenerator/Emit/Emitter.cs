    private bool SpanAvailable(TypeModel type) => type.Kind switch
    {
        TypeKind.Array => _model.Capabilities.HasReadOnlySpan,
        TypeKind.List => _model.Capabilities.HasReadOnlySpan && _model.Capabilities.HasCollectionsMarshal,
        _ => false,
    };

    private string SpanOf(TypeModel type, string value) => type.Kind == TypeKind.List
        ? $"global::System.Runtime.InteropServices.CollectionsMarshal.AsSpan({value})"
        : value;

    private string ElementHashForContainer(TypeModel container, TypeModel element, string value)
        => HashOrOmit(element, value, 1, container.ElementIsSameScc) ?? "0";

    private void EmitArrayOrListCores(TypeModel type)
    {
        TypeModel element = T(type.ElementTypeId);
        string p = Param(type);
        string count = type.Kind == TypeKind.Array ? "Length" : "Count";

        _w.Open($"private static bool Equals_{type.ShortName}({p} x, {p} y{StateParam(type)})");
        _w.Line($"if ({RefEq("x", "y")}) return true;");
        _w.Line($"if (x is null || y is null || x.{count} != y.{count}) return false;");
        if (type.IsGuarded)
        {
            _w.Line($"if (!state.TryEnter(Kind_{type.ShortName}, x, y)) return true;");
        }

        if (SpanAvailable(type))
        {
            _spanCores.Add(element.Id);
            _w.Line($"return Equals_SpanOf{element.ShortName}({SpanOf(type, "x")}, {SpanOf(type, "y")}{StateArg(type)});");
        }
        else
        {
            _w.Line($"int n = x.{count};");
            _w.Open("for (int i = 0; i < n; i++)");
            _w.Line($"if (!({Eq(element, "x[i]", "y[i]")})) return false;");
            _w.Close();
            _w.Line("return true;");
        }

        _w.Close();

        // Level 1 hash.
        _w.Open($"private static int GetHashCode_{type.ShortName}({p} o)");
        _w.Line("if (o is null) return 0;");
        if (SpanAvailable(type) && _model.Capabilities.HasFrameworkSpanHelpers)
        {
            string ops = type.ElementIsSameScc ? type.ShortName + "ShallowOps" : type.ShortName + "Ops";
            _w.Line($"return {KnownTypes.GlobalHashCode}.HashSpan<{element.GlobalName}, {ops}>({SpanOf(type, "o")});");
        }
        else
        {
            _w.Line($"{KnownTypes.GlobalHashCode}.Streaming h = default;");
            _w.Line($"int n = o.{count};");
            _w.Open("for (int i = 0; i < n; i++)");
            _w.Line($"h.Add({ElementHashForContainer(type, element, "o[i]")});");
            _w.Close();
            _w.Line("return h.ToHashCode();");
        }

        _w.Close();

        if (type.HasShallowHash)
        {
            _w.Line($"private static int ShallowHashCode_{type.ShortName}({p} o) => o is null ? 0 : (o.{count} == 0 ? 1 : o.{count});");
        }

        if (SpanAvailable(type) && _model.Capabilities.HasFrameworkSpanHelpers)
        {
            EmitHashOps(type, element);
        }

        _w.Line();
    }

    private void EmitHashOps(TypeModel container, TypeModel element)
    {
        string name = container.ElementIsSameScc ? container.ShortName + "ShallowOps" : container.ShortName + "Ops";
        _w.Open($"private struct {name} : {KnownTypes.GlobalHashOps}<{element.GlobalName}>");
        _w.Line($"public int GetHashCode({element.GlobalName} value) => {ElementHashForContainer(container, element, "value")};");
        _w.Close();
    }

    private void EmitSpanCores(TypeModel element)
    {
        bool needsState = element.NeedsState;
        string stateParam = needsState ? $", ref {KnownTypes.GlobalState} state" : string.Empty;
        string span = $"global::System.ReadOnlySpan<{element.GlobalName}>";
        _w.Open($"private static bool Equals_SpanOf{element.ShortName}({span} xs, {span} ys{stateParam})");
        _w.Line("if (xs.Length != ys.Length) return false;");
        if (element.Kind == TypeKind.Leaf && element.DefaultCompatible && element.ImplementsIEquatable && element.LeafRule != LeafRule.Custom && element.LeafRule != LeafRule.Enum)
        {
            _w.Line("return global::System.MemoryExtensions.SequenceEqual(xs, ys);");
        }
        else
        {
            _w.Open("for (int i = 0; i < xs.Length; i++)");
            _w.Line($"if (!({Eq(element, "xs[i]", "ys[i]")})) return false;");
            _w.Close();
            _w.Line("return true;");
        }

        _w.Close();
        _w.Line();
    }

    private void EmitListInterfaceCores(TypeModel type)
    {
        TypeModel element = T(type.ElementTypeId);
        string p = Param(type);
        string iface = type.CollectionInterfaceGlobalName.Length > 0 ? type.CollectionInterfaceGlobalName : type.GlobalName;

        _w.Open($"private static bool Equals_{type.ShortName}({p} x, {p} y{StateParam(type)})");
        _w.Line($"if ({RefEq("x", "y")}) return true;");
        _w.Line("if (x is null || y is null) return false;");
        EmitImmutablePreflight(element, "x", "y");
        _w.Line($"{iface} xi = x;");
        _w.Line($"{iface} yi = y;");
        _w.Line("int count = xi.Count;");
        _w.Line("if (count != yi.Count) return false;");
        if (type.IsGuarded)
        {
            _w.Line($"if (!state.TryEnter(Kind_{type.ShortName}, x, y)) return true;");
        }

        if (_model.Capabilities.HasFrameworkSpanHelpers)
        {
            _spanCores.Add(element.Id);
            _w.Line($"if ({KnownTypes.GlobalCollections}.TryGetSpan(x, out global::System.ReadOnlySpan<{element.GlobalName}> xs) && {KnownTypes.GlobalCollections}.TryGetSpan(y, out global::System.ReadOnlySpan<{element.GlobalName}> ys)) return Equals_SpanOf{element.ShortName}(xs, ys{(element.NeedsState ? ", ref state" : string.Empty)});");
