    /// <summary>Returns the nullable annotation symbol if it is availble, otherwise empty string.</summary>
    private string Q() => Annotations ? "?" : string.Empty;

    private string Param(TypeModel type) => type.IsValueType ? type.GlobalName : type.GlobalName + Q();

    /// <summary>
    /// Returns csharp-safe identifier for a name (@ prefixed if it is a keyword).
    /// </summary>
    private static string Identifier(string name) => 
        SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None ? $"@{name}" : name;

    private static string StateParam(TypeModel type) =>
        type.NeedsState ? $", ref {KnownTypes.GlobalState} state" : string.Empty;

    private static string StateArg(TypeModel type) => type.NeedsState ? ", ref state" : string.Empty;

    /// <summary>Call <see cref="object.ReferenceEquals"/></summary>
    private static string RefEq(string x, string y) => $"{KnownTypes.GlobalObject}.ReferenceEquals({x}, {y})";

    private static string Combine<T>(IEnumerable<T> inputs, Func<T, string> selector) => 
        Combine(inputs.Select(selector).ToList());
    
    private static string Combine(List<string> inputs)
    {
        while (true)
            switch (inputs.Count)
            {
                case 0:
                    return "1";
                case <= MaxCombineArity:
                    return ItemList($"{KnownTypes.GlobalHashCode}.Combine(", inputs, ",", ")");
                default:
                    inputs = Chunk(inputs);
                    break;
            }
        
        // 1 round of grouping: each group of at most MaxCombineArity inputs becomes a nested call
        static List<string> Chunk(List<string> inputs)
        {
            var nested = new List<string>(capacity: inputs.Count);
            for (var i = 0; i < inputs.Count; i += MaxCombineArity) 
                nested.Add(Combine(inputs.GetRange(i, Math.Min(MaxCombineArity, inputs.Count - i))));

            return nested;
        }
    }

    private void EmitPredicates<T>(IEnumerable<T> items, Func<T, string> selector, bool terminalReturnTrue) => 
        EmitPredicates(items.Select(selector).ToList(), terminalReturnTrue);
    
    /// <summary>
    /// Emits a predicate chain as chunks of at most MaxBinaryExpressionArity,
    /// returning false on the first failed chunk.
    /// </summary>
    private void EmitPredicates(List<string> predicates, bool terminalReturnTrue)
    {
        var arity = _model.Options.MaxBinaryExpressionArity;
        if (predicates.Count == 0)
        {
            if (terminalReturnTrue) 
                _w.Line("return true;");

            return;
        }

        if (predicates.Count <= arity && terminalReturnTrue)
        {
            // "return" alone on the first line, since a single predicate is the only case that fits beside it.
            _w.Line(ItemList(predicates.Count == 1 ? "return " : "return", predicates, " &&", ";"));
            return;
        }

        for (var i = 0; i < predicates.Count; i += arity)
        {
            var chunk = predicates.GetRange(i, Math.Min(arity, predicates.Count - i));
            _w.Line(ItemList("if (!(", chunk, " &&", ")) return false;"));
        }

        if (terminalReturnTrue) 
            _w.Line("return true;");
    }

    // ----- member reads ---------------------------------------------------------------------------------------------------

    /// <summary>
    /// The expression that reads a member from a receiver of the declaring type;
    /// <paramref name="inReceiver"/> when the receiver is an in parameter.
    /// </summary>
    private static string Read(MemberModel member, string receiver, bool inReceiver)
    {
        switch (member.Access)
        {
                        case MemberAccess.Direct:
                return $"{receiver}.{Identifier(member.FieldMetadataName)}";

            case MemberAccess.Getter:
                return $"{receiver}.{Identifier(member.Name)}";

            
            case MemberAccess.UnsafeAccessor:
                var accessor = member.GenericAccessor 
                    ? $"{member.GenericHolderName}{member.GenericTypeArguments}.{member.AccessorName}"
                    : member.AccessorName;
                return member.DeclaringTypeIsValueType
                    ? $"{accessor}(ref {WritableReceiver(receiver, inReceiver)})"
                    : $"{accessor}({receiver})";

            case MemberAccess.Delegate:
            default:
                return member.DeclaringTypeIsValueType
                    ? $"{member.DeclaringTypeShortName}_Accessors.{member.AccessorName}(ref {WritableReceiver(receiver, inReceiver)})"
                    : $"{member.DeclaringTypeShortName}_Accessors.{member.AccessorName}({receiver})";
        }
    }

    private static string WritableReceiver(string receiver, bool inReceiver) =>
        inReceiver ? $"{KnownTypes.GlobalHelpers}.AsWritableRef(in {receiver})" : receiver;

    // ----- equality expressions ---------------------------------------------------------------------------------------------

    /// <summary>A boolean expression comparing two values of <paramref name="type"/>; state is passed when the type needs it.</summary>
    private string Eq(TypeModel type, string x, string y)
    {
        switch (type.Kind)
        {
            case TypeKind.Leaf:
                return LeafEq(type, x, y);
            
            case TypeKind.Nullable:
                var payload = Type(type.PayloadTypeId);
                return $"({x}.HasValue == {y}.HasValue && (!{x}.HasValue || {Eq(payload, $"{x}.GetValueOrDefault()", $"{y}.GetValueOrDefault()")}))";
            
            case TypeKind.Struct:
                if (type.InlineAsSmallStruct)
                {
                    var predicates = type.Members.Select(m => Eq(Type(m.TypeId), Read(m, x, false), Read(m, y, false))).ToList();
                    return predicates.Count == 0 ? "true" : ItemList("(", predicates, " &&", ")");
                }

                // An `in` parameter binds by reference without the keyword at the call site; writing `in` would require a
                // variable, and arguments such as `e.Value` or `GetValueOrDefault()` are not (CS8156).
                return $"Equals_{type.ShortName}({x}, {y}{StateArg(type)})";
            
            default:
                return $"Equals_{type.ShortName}({x}, {y}{StateArg(type)})";
        }
    }

    private string LeafEq(TypeModel type, string x, string y)
    {
        switch (type.LeafRule)
        {
            case LeafRule.Primitive:
            case LeafRule.WideInteger:
            case LeafRule.Guid:
                return $"{x} == {y}";
            
            case LeafRule.Enum:
                return $"({type.EnumUnderlyingGlobalName}){x} == ({type.EnumUnderlyingGlobalName}){y}";
            
                        case LeafRule.String:
                return $"{x} == {y}";
            
            case LeafRule.Single:
                return $"{SingleBits(x)} == {SingleBits(y)}";
            
            case LeafRule.Double:
                return $"{KnownTypes.GlobalBitConverter}.DoubleToInt64Bits({x}) == {KnownTypes.GlobalBitConverter}.DoubleToInt64Bits({y})";
            
            case LeafRule.Half:
                return $"{KnownTypes.GlobalBitConverter}.HalfToInt16Bits({x}) == {KnownTypes.GlobalBitConverter}.HalfToInt16Bits({y})";
            
                        case LeafRule.Decimal:
                return $"{KnownTypes.GlobalHelpers}.DecimalEquals({x}, {y})";
            
            case LeafRule.DateTime:
                return $"{KnownTypes.GlobalHelpers}.DateTimeBits({x}) == {KnownTypes.GlobalHelpers}.DateTimeBits({y})";
            
            case LeafRule.DateTimeOffset:
                return $"({x}.Ticks == {y}.Ticks && {x}.Offset == {y}.Offset)";
            
            case LeafRule.FloatAggregate:
                // Matrix4x4 is sixteen of these; a component is as much a member as a property is.
                return ItemList("(", type.AggregateComponents.Select(c => c.IsDouble
                    ? $"{KnownTypes.GlobalBitConverter}.DoubleToInt64Bits({x}.{c.Expression}) == {KnownTypes.GlobalBitConverter}.DoubleToInt64Bits({y}.{c.Expression})"
                    : $"{SingleBits($"{x}.{c.Expression}")} == {SingleBits($"{y}.{c.Expression}")}").ToList(), " &&", ")");
            
            case LeafRule.Uri:
                return RefLeaf(x, y, 
                    $"(string.Equals({x}.OriginalString, {y}.OriginalString, {KnownTypes.GlobalStringComparison}.Ordinal) && {x}.IsAbsoluteUri == {y}.IsAbsoluteUri)");
            
            case LeafRule.Regex:
                return RefEq(x, y);
            
            case LeafRule.Custom:
                return CustomEq(type, x, y);
            
            case LeafRule.UserSimple:
            case LeafRule.Default:
            default:
                return type.IsValueType ? DefaultEq(type, x, y) : RefLeaf(x, y, DefaultEq(type, x, y));
        }
    }

    /// <summary>
    /// The default-equality rule for two non-null operands of the exact static type.
    /// A type implementing <c>IEquatable{Self}</c> is called directly:
    /// <c>x.Equals(y)</c> when that implementation is a public method on a struct or sealed class, otherwise through the constrained framework shim.
    /// Everything else, including a derived type that only inherits <c>IEquatable{Base}</c>, keeps <c>EqualityComparer{T}.Default</c>.
    /// Both direct forms are what the default comparer does for such a type after its null checks.
    /// </summary>
    private static string DefaultEq(TypeModel type, string x, string y)
    {
        if (!type.ImplementsIEquatable) 
            return $"{KnownTypes.GlobalEqualityComparer}<{type.GlobalName}>.Default.Equals({x}, {y})";

        return type is { HasPublicEquatableEquals: true, IsSealed: true }
            ? $"({x}).Equals({y})"
            : $"{KnownTypes.GlobalHelpers}.EquatableEquals<{type.GlobalName}>({x}, {y})";
    }

    private static string RefLeaf(string x, string y, string rule) => 
        $"({RefEq(x, y)} || (!({x} is null) && !({y} is null) && {rule}))";

    private string SingleBits(string value) => 
        _model.Capabilities.HasSingleToInt32Bits
            ? $"{KnownTypes.GlobalBitConverter}.SingleToInt32Bits({value})"
            : $"{KnownTypes.GlobalHelpers}.SingleToInt32Bits({value})";

    private string CustomEq(TypeModel type, string x, string y)
    {
        var custom = _model.CustomComparers[type.CustomComparerIndex];
        if (type.CustomWrapsNullable)
            return $"{custom.HolderName}.Value.Equals((global::System.Nullable<{type.GlobalName}>){x}, (global::System.Nullable<{type.GlobalName}>){y})";

        var call = $"{custom.HolderName}.Value.Equals({x}, {y})";
        if (custom.HandleNulls || (type.IsValueType && !IsNullableName(type))) 
            return call;

        return type.IsValueType 
            ? $"({x}.HasValue == {y}.HasValue && (!{x}.HasValue || {call}))" 
            : RefLeaf(x, y, call);
    }

    private static bool IsNullableName(TypeModel type) => type.GlobalName.EndsWith("?", StringComparison.Ordinal);

    // ----- hash expressions ------------------------------------------------------------------------------------------------

    /// <summary>The hash of a value reached through an edge; null means the edge is omitted at this level.</summary>
    private string? HashOrOmit(TypeModel type, string value, int level, bool sameScc)
    {
        switch (type.Kind)
        {
            case TypeKind.Leaf:
                return LeafHash(type, value);
            
            case TypeKind.Nullable:
                var payload = HashOrOmit(Type(type.PayloadTypeId), $"{value}.GetValueOrDefault()", level, sameScc);
                return payload is null ? null : $"({value}.HasValue ? {payload} : 0)";
            
            case TypeKind.Struct:
                if (type.InlineAsSmallStruct) 
                    return Combine(type.Members,
                        m => LeafHash(Type(m.TypeId), Read(m, value, false)));

                break;
        }

        var container = IsContainerOrProduct(type);
        if (level == 1)
        {
            if (container) 
                return $"GetHashCode_{type.ShortName}({value})";
            return sameScc ? $"ShallowHashCode_{type.ShortName}({value})" : $"GetHashCode_{type.ShortName}({value})";
        }

        if (sameScc) 
            return container ? $"ShallowHashCode_{type.ShortName}({value})" : null;

        return $"GetHashCode_{type.ShortName}({value})";
    }

        /// <summary>
    /// The words a member contributes to its owner's hash stream, in statement context. A leaf wider than 32 bits is
    /// read once into a local named <paramref name="local"/> and split into its words, so the owner mixes them into one
    /// seeded stream instead of finishing a nested hash per member; an inlined struct contributes its members' words.
    /// Everything else contributes the single word of its own hash, or nothing when the level omits it.
    /// </summary>
    private void HashWords(TypeModel type, string value, int level, bool sameScc, string local, List<string> words)
    {
        switch (type.Kind)
        {
            case TypeKind.Leaf when WideLeafWords(type, value, local, words):
                return;

            case TypeKind.Struct when type.InlineAsSmallStruct:
                var k = 0;
                foreach (var member in type.Members)
                    HashWords(Type(member.TypeId), Read(member, value, false), level, sameScc, $"{local}_{k++}", words);

                return;
        }

        var single = HashOrOmit(type, value, level, sameScc);
        if (single is not null)
            words.Add(single);
    }

    /// <summary>Reads a wide leaf into <paramref name="local"/> and appends its 32-bit words; false when the leaf is not wide.</summary>
    private bool WideLeafWords(TypeModel type, string value, string local, List<string> words)
    {
        switch (type.LeafRule)
        {
            case LeafRule.WideInteger:
                if (type.GlobalName.EndsWith("Int128", StringComparison.Ordinal))
                    return false;   // keeps its own seeded hash

                var unsigned = type.GlobalName is "ulong" or "nuint" || type.GlobalName.EndsWith("UIntPtr", StringComparison.Ordinal);
                _w.Line(unsigned ? $"ulong {local} = (ulong){value};" : $"long {local} = (long){value};");
                Words64(local, words);
                return true;

            case LeafRule.Enum:
                if (type.EnumUnderlyingWidth != 8)
                    return false;

                _w.Line(type.EnumUnderlyingUnsigned ? $"ulong {local} = (ulong){value};" : $"long {local} = (long){value};");
                Words64(local, words);
                return true;

            case LeafRule.Double:
                _w.Line($"long {local} = {KnownTypes.GlobalBitConverter}.DoubleToInt64Bits({value});");
                Words64(local, words);
                return true;

            case LeafRule.DateTime:
                _w.Line($"ulong {local} = {KnownTypes.GlobalHelpers}.DateTimeBits({value});");
                Words64(local, words);
                return true;

            case LeafRule.DateTimeOffset:
                _w.Line($"global::System.DateTimeOffset {local} = {value};");
                _w.Line($"long {local}t = {local}.Ticks;");
                _w.Line($"long {local}o = {local}.Offset.Ticks;");
                Words64($"{local}t", words);
                Words64($"{local}o", words);
                return true;

            case LeafRule.Guid:
                _w.Line($"global::System.Guid {local} = {value};");
                for (var i = 0; i < 4; i++)
                    words.Add($"{KnownTypes.GlobalHelpers}.GuidWord({local}, {i})");

                return true;

            case LeafRule.Decimal:
                _w.Line($"decimal {local} = {value};");
                for (var i = 0; i < 4; i++)
                    words.Add($"{KnownTypes.GlobalHelpers}.DecimalWord({local}, {i})");

                return true;

            case LeafRule.FloatAggregate:
                _w.Line($"{type.GlobalName} {local} = {value};");
                var k = 0;
                foreach (var component in type.AggregateComponents)
                {
                    if (component.IsDouble)
                    {
                        _w.Line($"long {local}_{k} = {KnownTypes.GlobalBitConverter}.DoubleToInt64Bits({local}.{component.Expression});");
                        Words64($"{local}_{k}", words);
                    }
                    else
                    {
                        words.Add(SingleBits($"{local}.{component.Expression}"));
                    }

                    k++;
                }

                return true;

            default:
                return false;
        }
    }

    private static void Words64(string local, List<string> words)
    {
        words.Add($"unchecked((int){local})");
        words.Add($"unchecked((int)({local} >> 32))");
    }

    private static bool IsContainerOrProduct(TypeModel type) => type.Kind is  
        TypeKind.Array or TypeKind.List or TypeKind.ImmutableArray or TypeKind.ArraySegment or TypeKind.Memory or 
        TypeKind.ListInterface or TypeKind.EnumerableInterface or TypeKind.Set or TypeKind.Dictionary or 
        TypeKind.KeyValuePair or TypeKind.ValueTuple or TypeKind.Tuple;

    private string LeafHash(TypeModel type, string value)
    {
        switch (type.LeafRule)
        {
            case LeafRule.Primitive:
                return PrimitiveHash(type, value);
            case LeafRule.WideInteger:
                if (type.GlobalName.EndsWith("IntPtr", StringComparison.Ordinal)) 
                    return type.GlobalName.EndsWith("UIntPtr", StringComparison.Ordinal) 
                        ? $"{KnownTypes.GlobalHashCode}.Hash((ulong){value})" 
                        : $"{KnownTypes.GlobalHashCode}.Hash((long){value})";

                if (type.GlobalName.EndsWith("Int128", StringComparison.Ordinal) && !_model.Capabilities.HasFrameworkHash128)
                    // The resolved framework asset predates Int128: seed both 64-bit halves through the long overload.
                    return $"{KnownTypes.GlobalHashCode}.Combine({KnownTypes.GlobalHashCode}.Hash(unchecked((long){value})), {KnownTypes.GlobalHashCode}.Hash(unchecked((long)({value} >> 64))))";

                return $"{KnownTypes.GlobalHashCode}.Hash({value})";
            
            case LeafRule.Guid:
                return $"{KnownTypes.GlobalHashCode}.Hash({value})";
            
            case LeafRule.Enum:
                return type.EnumUnderlyingWidth switch
                {
                    8 => type.EnumUnderlyingUnsigned ? $"{KnownTypes.GlobalHashCode}.Hash((ulong){value})" : $"{KnownTypes.GlobalHashCode}.Hash((long){value})",
                    4 => type.EnumUnderlyingUnsigned ? $"unchecked((int)(uint){value})" : $"(int){value}",
                    _ => $"(int)({type.EnumUnderlyingGlobalName}){value}",
                };
            
            case LeafRule.String:
                return $"{KnownTypes.GlobalHashCode}.Hash({value})";
            
            case LeafRule.Single:
                return SingleBits(value);
            
            case LeafRule.Double:
                return $"{KnownTypes.GlobalHashCode}.Hash({KnownTypes.GlobalBitConverter}.DoubleToInt64Bits({value}))";
            
            case LeafRule.Half:
                return $"(int){KnownTypes.GlobalBitConverter}.HalfToInt16Bits({value})";
            
                        case LeafRule.Decimal:
                return $"{KnownTypes.GlobalHashCode}.Hash({value})";
            
            case LeafRule.DateTime:
                return $"{KnownTypes.GlobalHashCode}.Hash({KnownTypes.GlobalHelpers}.DateTimeBits({value}))";
            
            case LeafRule.DateTimeOffset:
                return $"{KnownTypes.GlobalHashCode}.Combine({KnownTypes.GlobalHashCode}.Hash({value}.Ticks), {KnownTypes.GlobalHashCode}.Hash({value}.Offset.Ticks))";
            
            case LeafRule.FloatAggregate:
                return Combine(type.AggregateComponents,
                    c => c.IsDouble
                        ? $"{KnownTypes.GlobalHashCode}.Hash({KnownTypes.GlobalBitConverter}.DoubleToInt64Bits({value}.{c.Expression}))"
                        : SingleBits($"{value}.{c.Expression}"));
            
            case LeafRule.Uri:
                return $"({value} is null ? 0 : {KnownTypes.GlobalHashCode}.Combine({KnownTypes.GlobalHashCode}.Hash({value}.OriginalString), {value}.IsAbsoluteUri ? 1 : 0))";
            
            case LeafRule.Regex:
                return $"{KnownTypes.GlobalRuntimeHelpers}.GetHashCode({value})";
            
            case LeafRule.Custom:
                return CustomHash(type, value);
            
            case LeafRule.UserSimple:
            case LeafRule.Default:
            default:
                return type.IsValueType
                    ? $"{value}.GetHashCode()"
                    : $"({value} is null ? 0 : {value}.GetHashCode())";
        }
    }

    private static string PrimitiveHash(TypeModel type, string value) =>
        type.GlobalName switch
        {
            "int" => value,
            "uint" => $"unchecked((int){value})",
            "bool" => $"({value} ? 1 : 0)",
            _ => $"(int){value}"
        };

    private string CustomHash(TypeModel type, string value)
    {
        var custom = _model.CustomComparers[type.CustomComparerIndex];
        if (type.CustomWrapsNullable)
            return $"{custom.HolderName}.Value.GetHashCode((global::System.Nullable<{type.GlobalName}>){value})";

        var call = $"{custom.HolderName}.Value.GetHashCode({value})";
        if (custom.HandleNulls || (type.IsValueType && !IsNullableName(type))) 
            return call;

        return type.IsValueType 
            ? $"({value}.HasValue ? {call} : 0)" 
            : $"({value} is null ? 0 : {call})";
    }

    // ----- wrappers -----------------------------------------------------------------------------------------------------

    private void EmitWrapper(TypeModel type)
    {
        var name = $"{type.ShortName}EqualityComparer";
        _w.Line($"[global::System.CodeDom.Compiler.GeneratedCode(\"DeepEquals.SourceGenerator\", \"{GeneratorVersion}\")]");
        
        // A reference-type wrapper accepts null on both sides, so under nullable annotations it implements IEqualityComparer<T?>.
        using (_w.Block($"{type.Accessibility} sealed class {name} : {KnownTypes.GlobalIEqualityComparer}<{Param(type)}>"))
        {
            _w.Line($"public static readonly {name} Instance = new {name}();");
            _w.Line($"private {name}() {{ }}");
            _w.Line();
            
            // The comparer for object declares an instance Equals(object, object),
            // which hides the static one every class inherits from object; `new` states that this is meant.
            using (Method(type, $"public {(type.IsObject ? "new " : string.Empty)}bool Equals({Param(type)} x, {Param(type)} y)"))
                        {
                // Only a closure with a cycle can recurse without bound, and only its Equals: the hash stops one payload
                // edge into a cycle, and an acyclic closure is as deep as its declarations. Every cycle also passes
                // through a guard, whose TryEnter checks the stack again at each turn.
                var body = WrapperEqualsBody(type);
                if (type.NeedsState)
                {
                    _w.Line($"{KnownTypes.GlobalRuntimeHelpers}.EnsureSufficientExecutionStack();");
                    _w.Line($"{KnownTypes.GlobalState} state = new {KnownTypes.GlobalState}(MaxComparisonPairs);");
                    using (_w.Block("try"))
                        _w.Return(body);
                    using (_w.Block("finally")) 
                        _w.Line("state.Dispose();");
                }
                else
                {
                    _w.Return(body);
                }
            }
            
            _w.Line();
            using (Method(type, $"public int GetHashCode({Param(type)} o)"))
                        {
                _w.Return(WrapperHashBody(type));
            }
        }
        _w.Line();
    }

    private string WrapperEqualsBody(TypeModel type) => Eq(type, "x", "y");

    private string WrapperHashBody(TypeModel type)
    {
        var hash = HashOrOmit(type, "o", 1, sameScc: false);
        return hash ?? "1";
    }

    // ----- cores per kind ----------------------------------------------------------------------------------------------------

    private void EmitCores(TypeModel type)
    {
        switch (type.Kind)
        {
                        case TypeKind.Leaf:
                break;
            case TypeKind.Nullable:
                break;
            
            case TypeKind.Class:
                EmitClassCores(type);
                break;
            
            case TypeKind.Struct:
                EmitStructCores(type);
                break;
            
            case TypeKind.Dispatch:
                EmitDispatchCores(type);
                break;
            
            case TypeKind.Array:
            case TypeKind.List:
                EmitArrayOrListCores(type);
                break;
            
            case TypeKind.ListInterface:
                EmitListInterfaceCores(type);
                break;
            
            case TypeKind.EnumerableInterface:
                EmitEnumerableCores(type);
                break;
            
            case TypeKind.Set:
            case TypeKind.Dictionary:
                EmitUnorderedCores(type);
                break;
            
            case TypeKind.KeyValuePair:
            case TypeKind.ValueTuple:
            case TypeKind.Tuple:
                EmitProductCores(type);
                break;
            
            case TypeKind.Memory:
            case TypeKind.ImmutableArray:
            case TypeKind.ArraySegment:
                EmitValueSequenceCores(type);
                break;
            
            default:
                throw new NotSupportedException($"The {type.Kind} shape ({type.GlobalName}) is not implemented by this generator version yet.");
        }

        if (type.HasBoxedAdapter && type.Kind != TypeKind.Struct) 
            EmitBoxedAdapter(type);
    }

    /// <summary>
    /// The reference-valued guard boundary of a boxed value shape:
    /// guards on the original boxes, then unboxes into the value body.
    /// </summary>
    private void EmitBoxedAdapter(TypeModel type)
    {
        var unboxX = Unbox(type, "x");
        var unboxY = Unbox(type, "y");
        var stateParam = type.BoxedAdapterGuarded || type.NeedsState ? $", ref {KnownTypes.GlobalState} state" : string.Empty;
        using (_w.Block($"private static bool EqualsBoxed_{type.ShortName}(object x, object y{stateParam})"))
        {
            EmitCycleGuard(type, boxed: true);
            _w.Return($"Equals_{type.ShortName}({unboxX}, {unboxY}{StateArg(type)})");
        }
        _w.Line();
    }

    /// <summary>Memory, ReadOnlyMemory, ImmutableArray and ArraySegment: value shapes whose represented sequence is compared in order.</summary>
    private void EmitValueSequenceCores(TypeModel type)
    {
        var element = Type(type.ElementTypeId);
        var p = type.GlobalName;
        var spans = _model.Capabilities.HasReadOnlySpan;
        var span = $"global::System.ReadOnlySpan<{element.GlobalName}>";

        using (_w.Block($"private static bool Equals_{type.ShortName}({p} x, {p} y{StateParam(type)})"))
        {
            switch (type.Kind)
            {
                case TypeKind.Memory:
                    _w.Line("if (x.Length != y.Length) return false;");
                    _spanCores.Add(element.Id);
                    _w.Return($"Equals_SpanOf{element.ShortName}(x.Span, y.Span{(element.NeedsState ? ", ref state" : string.Empty)})");
                    break;
            
                case TypeKind.ImmutableArray:
                    _w.Line("if (x.IsDefault || y.IsDefault) return x.IsDefault && y.IsDefault;");
                    _w.Line("if (x.Length != y.Length) return false;");
                    if (spans)
                    {
                        _spanCores.Add(element.Id);
                        _w.Return($"Equals_SpanOf{element.ShortName}(x.AsSpan(), y.AsSpan(){(element.NeedsState ? ", ref state" : string.Empty)})");
                    }
                    else
                    {
                        _w.Line("int n = x.Length;");
                        using (_w.For("n")) _w.Line($"if (!({Eq(element, "x[i]", "y[i]")})) return false;");
                        _w.Return("true");
                    }
                
                    break;
            
                default:
                    _w.Line("if (x.Count != y.Count) return false;");
                    _w.Line("if (x.Count == 0) return true;");
                    if (spans)
                    {
                        _spanCores.Add(element.Id);
                        _w.Return($"Equals_SpanOf{element.ShortName}(({span})x, ({span})y{(element.NeedsState ? ", ref state" : string.Empty)})");
                    }
                    else
                    {
                        _w.Line("int n = x.Count;");
                        using (_w.For("n")) _w.Line($"if (!({Eq(element, "x.Array![x.Offset + i]", "y.Array![y.Offset + i]").Replace("![", Annotations ? "![" : "[")})) return false;");
                        _w.Return("true");
                    }

                    break;
            }

        }

        // Level 1 hash over the represented sequence; ImmutableArray default hashes to 0.
        using (_w.Block($"private static int GetHashCode_{type.ShortName}({p} o)"))
        {
            if (type.Kind == TypeKind.ImmutableArray) 
                _w.Line("if (o.IsDefault) return 0;");

            var spanOf = type.Kind switch
            {
                TypeKind.Memory => "o.Span",
                TypeKind.ImmutableArray => "o.AsSpan()",
                _ => $"({span})o",
            };
            if (spans && _model.Capabilities.HasFrameworkSpanHelpers)
            {
                if (type.Kind == TypeKind.ArraySegment) 
                    _w.Line("if (o.Count == 0) return 1;");
                var ops = type.ElementIsSameScc ? $"{type.ShortName}ShallowOps" : $"{type.ShortName}Ops";
                _w.Return($"{KnownTypes.GlobalHashCode}.HashSpan<{element.GlobalName}, {ops}>({spanOf})");
            }
            else
            {
                // The three walks differ only in what they iterate and how an element is read.
                var (local, limit, item) = type.Kind == TypeKind.ArraySegment
                    ? ("int n = o.Count;", "n", "o.Array[o.Offset + i]")
                    : spans
                        ? ($"{span} s = {spanOf};", "s.Length", "s[i]")
                        : ("int n = o.Length;", "n", "o[i]");
                _w.Line($"{KnownTypes.GlobalHashCode}.Streaming h = default;");
                _w.Line(local);
                using (_w.For(limit)) 
                    _w.Line($"h.Add({ElementHashForContainer(type, element, item)});");
                _w.Return("h.ToHashCode()");
            }
        }

        if (type.HasShallowHash)
        {
            var count = type.Kind == TypeKind.ArraySegment ? "o.Count" : "o.Length";
            var guard = type.Kind == TypeKind.ImmutableArray ? "o.IsDefault ? 0 : " : string.Empty;
            _w.Arrow(
                $"private static int ShallowHashCode_{type.ShortName}({p} o)", 
                $"{guard}({count} == 0 ? 1 : {count})");
        }

        if (spans && _model.Capabilities.HasFrameworkSpanHelpers) 
            EmitHashOps(type, element);

        _w.Line();
    }

    // ----- classes ------------------------------------------------------------------------------------------------------------

    private void EmitClassCores(TypeModel type)
    {
        var p = Param(type);
        var dispatch = !type.IsSealed;

        // Equals_T: the entry core.
        using (Method(type, $"private static bool Equals_{type.ShortName}({p} x, {p} y{StateParam(type)})"))
        {
            if (dispatch)
            {
                EmitDispatchEqualsBody(type);
            }
            else if (type.TailMemberIndex >= 0)
            {
                using (_w.Block("while (true)"))
                {
                    EmitReferencePrelude();
                    EmitCycleGuard(type);

                    var predicates = type.Members
                        .Where((_, i) => i != type.TailMemberIndex)
                        .Select(t => MemberEq(t, type, "x", "y"))
                        .ToList();

                    EmitPredicates(predicates, false);
                    var tail = type.Members[type.TailMemberIndex];
                    _w.Line($"{type.GlobalName}{Q()} nextX = {Read(tail, "x", false)};");
                    _w.Line($"{type.GlobalName}{Q()} nextY = {Read(tail, "y", false)};");
                    _w.Line("x = nextX;");
                    _w.Line("y = nextY;");
                }
            }
            else
            {
                EmitReferencePrelude();
                EmitCycleGuard(type);

                _w.Return($"EqualsMembers_{type.ShortName}(x, y{StateArg(type)})");
            }

        }

        // EqualsMembers_T: the member chain, called from dispatch cores and from Equals_T.
        using (Method(type, $"private static bool EqualsMembers_{type.ShortName}({type.GlobalName} x, {type.GlobalName} y{StateParam(type)})"))
            EmitPredicates(type.Members, m => MemberEq(m, type, "x", "y"), true);

        if (type.IsGuarded)
        {
            using (_w.Block($"private static bool EqualsExact_{type.ShortName}({type.GlobalName} x, {type.GlobalName} y, ref {KnownTypes.GlobalState} state)"))
            {
                EmitCycleGuard(type);
                _w.Return($"EqualsMembers_{type.ShortName}(x, y, ref state)");
            }
        }

        // Hashes.
        if (dispatch)
        {
            EmitDispatchHash(type, level: 1);
            if (type.HasShallowHash) 
                EmitDispatchHash(type, level: 0);

            EmitMembersHash(type, level: 1, membersOnly: true);
            if (type.HasShallowHash) 
                EmitMembersHash(type, level: 0, membersOnly: true);
        }
        else
        {
            EmitMembersHash(type, level: 1, membersOnly: false);
            if (type.HasShallowHash) 
                EmitMembersHash(type, level: 0, membersOnly: false);
        }

        _w.Line();
    }

    private string MemberEq(MemberModel member, TypeModel owner, string x, string y)
    {
        var inReceiver = owner is { Kind: TypeKind.Struct, PassByValue: false };
        return Eq(
            Type(member.TypeId),
            HoistedRead(member, x, inReceiver, "X"),
            HoistedRead(member, y, inReceiver, "Y"));
    }

    /// <summary>A delegate-accessor read of a struct or nullable member is evaluated once into a local; every other read is inline.</summary>
    private string HoistedRead(MemberModel member, string receiver, bool inReceiver, string suffix)
    {
        var type = Type(member.TypeId);
        var copies = 
            member.Access == MemberAccess.Delegate && 
            (type.Kind == TypeKind.Nullable || type.Kind == TypeKind.Struct || IsContainerOrProduct(type) && type.IsValueType);
        if (!copies)
            return Read(member, receiver, inReceiver);

        var local = $"h{member.DeclarationOrder}_{suffix}";
        _w.Line($"{Param(type)} {local} = {Read(member, receiver, inReceiver)};");
        return local;
    }

    /// <summary>
    /// GetHashCode_T / ShallowHashCode_T (null-checked entry) or
    /// HashMembers_T / ShallowHashMembers_T (members only, for dispatch).
    /// </summary>
    private void EmitMembersHash(TypeModel type, int level, bool membersOnly)
    {
        var name = membersOnly
            ? (level == 1 ? "HashMembers_" : "ShallowHashMembers_") + type.ShortName
            : (level == 1 ? "GetHashCode_" : "ShallowHashCode_") + type.ShortName;
        var inReceiver = type is { Kind: TypeKind.Struct, PassByValue: false };
        var param = type.Kind == TypeKind.Struct 
            ? inReceiver ? $"in {type.GlobalName} o" : $"{type.GlobalName} o" 
            : membersOnly ? $"{type.GlobalName} o" : $"{Param(type)} o";
        using (Method(type, $"private static int {name}({param})"))
        {
            if (!membersOnly && type.Kind == TypeKind.Class) 
                _w.Line("if (o is null) return 0;");

                        var inputs = new List<string>(type.Members.Count);
            foreach (var member in type.Members)
                HashWords(Type(member.TypeId), HoistedRead(member, "o", inReceiver, "O"), level, member.IsSameScc, $"w{member.DeclarationOrder}", inputs);

            _w.Return(Combine(inputs));
        }
    }

    // ----- structs ------------------------------------------------------------------------------------------------------------

    private void EmitStructCores(TypeModel type)
    {
        var param = type.PassByValue ? $"{type.GlobalName}" : $"in {type.GlobalName}";
        using (Method(type, $"private static bool Equals_{type.ShortName}({param} x, {param} y{StateParam(type)})"))
            EmitPredicates(type.Members, m => MemberEq(m, type, "x", "y"), true);

        if (type.HasBoxedAdapter) 
            EmitBoxedAdapter(type);

        EmitMembersHash(type, level: 1, membersOnly: false);
        if (type.HasShallowHash) 
            EmitMembersHash(type, level: 0, membersOnly: false);

        _w.Line();
    }

    // ----- dispatch -----------------------------------------------------------------------------------------------------------

    private void EmitDispatchCores(TypeModel type)
    {
        var p = Param(type);
        using (_w.Block($"private static bool Equals_{type.ShortName}({p} x, {p} y{StateParam(type)})")) EmitDispatchEqualsBody(type);
        
        EmitDispatchHash(type, level: 1);
        if (type.HasShallowHash) 
            EmitDispatchHash(type, level: 0);
        
        _w.Line();
    }

    private void EmitDispatchEqualsBody(TypeModel type)
    {
        EmitReferencePrelude();

                var assignable = type.Cases.Where(c => !c.IsExact).ToList();
        var exact = type.Cases.Where(c => c.IsExact).ToList();

        // Sealed assignable cases no earlier case accepts, string above all: one method-table compare each.
        foreach (var c in assignable.Where(c => c.Hoistable))
            EmitAssignableCaseEquals(c, bothSides: false);

        // Runtime types the closure knows come first: a sealed or value type is one method-table compare, an unsealed
        // class one GetType compare, and above MaxSwitchCases one lookup in a prebuilt map. Each lands where the
        // assignable chain below would have sent it.
                if (exact.Count > _model.Options.MaxSwitchCases)
        {
            // The leaves that dominate real payloads cost one method-table compare each, ahead of the map lookup.
            foreach (var c in HotLeafCases(exact))
            {
                using (_w.Block($"if ({ExactTest("x", Type(c.TypeId))})"))
                    EmitKnownCaseEquals(type, c, assignable);
            }

            using (_w.Block($"switch ({type.ShortName}_Dispatch.CaseIndex.TryGetValue(x.GetType(), out int i) ? i : -1)"))
            {
                for (var k = 0; k < exact.Count; k++)
                {
                    _w.Line($"case {k}:");
                    using (_w.Block())
                        EmitKnownCaseEquals(type, exact[k], assignable);
                }

                _w.Line("default: break;");
            }

            _pendingDispatchHolders.Add((type, exact));
        }
        else
        {
            foreach (var c in exact)
            {
                using (_w.Block($"if ({ExactTest("x", Type(c.TypeId))})"))
                    EmitKnownCaseEquals(type, c, assignable);
            }
        }

                // Runtime types the closure does not know: the first assignable case each side matches decides. A hoisted case
        // has already taken every x of its type; only its y test is left to do.
        foreach (var c in assignable)
        {
            if (c.Hoistable)
                _w.Line($"if (y is {Type(c.TypeId).GlobalName}) return false;");
            else
                EmitAssignableCaseEquals(c, bothSides: true);
        }

        // Neither side matched a case: different runtime types are unequal, the same unknown type cannot be compared.
        _w.Line("if (x.GetType() != y.GetType()) return false;");
        _w.Line($"throw new {KnownTypes.GlobalUnknownTypeException}(x.GetType());");
    }

        /// <summary>
    /// An assignable case: both sides must match it, and its rule decides. <paramref name="bothSides"/> adds the test that
    /// a y matching it, when x did not, is unequal.
    /// </summary>
    private void EmitAssignableCaseEquals(DispatchCase c, bool bothSides)
    {
        var target = Type(c.TypeId);
        var local = $"c{c.TypeId}";
        using (_w.Block($"if (x is {target.GlobalName} x{local})"))
        {
            _w.Line($"if (!(y is {target.GlobalName} y{local})) return false;");
            _w.Return($"{AssignableEq(target, $"x{local}", $"y{local}")}");
        }

        if (bothSides)
            _w.Line($"if (y is {target.GlobalName}) return false;");
    }

    /// <summary>
    /// The body of a known exact case, with <c>x</c> established as the case type: the other side must be the same
    /// exact type, or, when the case type converts to an assignable case, must match that case as the chain would demand.
    /// </summary>
    private void EmitKnownCaseEquals(TypeModel type, DispatchCase c, List<DispatchCase> assignable)
    {
        var target = Type(c.TypeId);
        if (c.ResolvedAssignable >= 0)
        {
            var a = Type(assignable[c.ResolvedAssignable].TypeId);
            var local = $"y{a.Id}";
            _w.Line($"if (!(y is {a.GlobalName} {local})) return false;");
            _w.Return(AssignableEq(a, AsCase(a, "x"), local));
            return;
        }

        _w.Line($"if (!({ExactTest("y", target)})) return false;");
        _w.Return(ExactEq(type, target));
    }

        /// <summary>The built-in leaves that most object-typed values are, in the order they are tested ahead of a dispatch map.</summary>
    private static readonly string[] HotLeafNames =
        ["string", "int", "long", "decimal", "double", "bool", "global::System.Guid", "global::System.DateTime", "global::System.DateTimeOffset"];

    /// <summary>The exact cases among <see cref="HotLeafNames"/> that land on their own rule, in that order.</summary>
    private IEnumerable<DispatchCase> HotLeafCases(List<DispatchCase> exact) =>
        HotLeafNames
            .Select(name => exact.FirstOrDefault(c => c.ResolvedAssignable < 0 && Type(c.TypeId) is { Kind: TypeKind.Leaf } t && t.GlobalName == name))
            .Where(c => c is not null)!;

    /// <summary>
    /// An exact runtime-type test the JIT lowers to a method-table compare: <c>is</c> for a sealed or value type,
    /// where it is exact, and <c>GetType() == typeof</c> for an unsealed class and for <c>object</c> itself.
    /// </summary>
    private static string ExactTest(string value, TypeModel target) =>
        !target.IsObject && (target.IsSealed || target.IsValueType) && !target.GlobalName.StartsWith("(", StringComparison.Ordinal)
            ? $"{value} is {target.GlobalName}"
            : $"{value}.GetType() == typeof({target.GlobalName})";   // tuple syntax after `is` is a pattern, not a type, before C# 9

    /// <summary>A known reference viewed as an assignable case type, which is always a reference type, without a cast check.</summary>
    private static string AsCase(TypeModel caseType, string value) =>
        caseType.IsValueType ? $"(({caseType.GlobalName}){value})" : $"{KnownTypes.GlobalUnsafe}.As<{caseType.GlobalName}>({value})";

    /// <summary>The Dictionary{Type, int} holders of large dispatch shapes, emitted after the cores of the type that asked for them.</summary>
    private void EmitDispatchHolders()
    {
        foreach (var (type, exact) in _pendingDispatchHolders)
        {
            using (_w.Block($"private static class {type.ShortName}_Dispatch"))
            {
                _w.Line($"static {type.ShortName}_Dispatch() {{ }}");
                _w.Line($"internal static readonly global::System.Collections.Generic.Dictionary<{KnownTypes.GlobalType}, int> CaseIndex = Build();");
                using (_w.Block($"private static global::System.Collections.Generic.Dictionary<{KnownTypes.GlobalType}, int> Build()"))
                {
                    _w.Line($"global::System.Collections.Generic.Dictionary<{KnownTypes.GlobalType}, int> map = new global::System.Collections.Generic.Dictionary<{KnownTypes.GlobalType}, int>({exact.Count});");
                    for (var k = 0; k < exact.Count; k++)
                        _w.Line($"map.Add(typeof({Type(exact[k].TypeId).GlobalName}), {k});");

                    _w.Return("map");
                }
            }
            _w.Line();
        }

        _pendingDispatchHolders.Clear();
    }

    /// <summary>
    /// Equality of two operands that both selected an assignable case;
    /// the operands are non-null and typed as the case.
    /// </summary>
    private string AssignableEq(TypeModel target, string x, string y)
    {
        if (target.Kind != TypeKind.Leaf) 
            return Eq(target, x, y);
        
        switch (target.LeafRule)
        {
            case LeafRule.Custom:
                var custom = _model.CustomComparers[target.CustomComparerIndex];
                return $"{custom.HolderName}.Value.Equals({x}, {y})";
            
            case LeafRule.UserSimple:
            case LeafRule.Default:
                return DefaultEq(target, x, y);
            
            default:
                return LeafEq(target, x, y);
        }
    }

    /// <summary>
    /// Equality of two operands whose exact runtime type is the case;
    /// lands past the reference, null and type checks.
    /// </summary>
    private string ExactEq(TypeModel dispatch, TypeModel target)
    {
        if (target.IsObject)
            return "true";   // two non-null values whose runtime type is exactly object have no state to differ in

        var stateArg = StateArg(target);
        switch (target.Kind)
        {
            case TypeKind.Class:
                if (target.Id == dispatch.Id)
                    return target.IsGuarded
                        ? $"EqualsExact_{target.ShortName}(x, y, ref state)"
                        : $"EqualsMembers_{target.ShortName}(x, y{stateArg})";

                var cx = $"{KnownTypes.GlobalUnsafe}.As<{target.GlobalName}>(x)";
                var cy = $"{KnownTypes.GlobalUnsafe}.As<{target.GlobalName}>(y)";
                return target.IsGuarded
                    ? $"EqualsExact_{target.ShortName}({cx}, {cy}, ref state)"
                    : $"EqualsMembers_{target.ShortName}({cx}, {cy}{stateArg})";
            
            case TypeKind.Struct:
                return target.BoxedAdapterGuarded
                    ? $"EqualsBoxed_{target.ShortName}(x, y, ref state)" 
                    : $"Equals_{target.ShortName}({Unbox(target, "x")}, {Unbox(target, "y")}{stateArg})";

            case TypeKind.Leaf:
                return LeafEq(target, $"(({target.GlobalName})x)", $"(({target.GlobalName})y)");
            
            case TypeKind.Tuple:
                return $"Equals_{target.ShortName}({KnownTypes.GlobalUnsafe}.As<{target.GlobalName}>(x), {KnownTypes.GlobalUnsafe}.As<{target.GlobalName}>(y){stateArg})";
            
            default:
                if (target.BoxedAdapterGuarded) 
                    return $"EqualsBoxed_{target.ShortName}(x, y, ref state)";

                return target.IsValueType
                    ? $"Equals_{target.ShortName}({Unbox(target, "x")}, {Unbox(target, "y")}{stateArg})"
                    : $"Equals_{target.ShortName}({KnownTypes.GlobalUnsafe}.As<{target.GlobalName}>(x), {KnownTypes.GlobalUnsafe}.As<{target.GlobalName}>(y){stateArg})";
        }
    }

    private static string Unbox(TypeModel target, string value) 
        => $"{KnownTypes.GlobalUnsafe}.Unbox<{target.GlobalName}>({value})";

    private void EmitDispatchHash(TypeModel type, int level)
    {
        var name = (level == 1 ? "GetHashCode_" : "ShallowHashCode_") + type.ShortName;
        using (_w.Block($"private static int {name}({Param(type)} o)"))
        {
            _w.Line("if (o is null) return 0;");
                        var assignable = type.Cases.Where(c => !c.IsExact).ToList();
            var exact = type.Cases.Where(c => c.IsExact).ToList();

            foreach (var c in assignable.Where(c => c.Hoistable))
                EmitAssignableCaseHash(type, c, level);

            if (exact.Count > _model.Options.MaxSwitchCases)
            {
                foreach (var c in HotLeafCases(exact))
                    _w.Line($"if ({ExactTest("o", Type(c.TypeId))}) return {KnownCaseHash(type, c, assignable, level)};");

                using (_w.Block($"switch ({type.ShortName}_Dispatch.CaseIndex.TryGetValue(o.GetType(), out int i) ? i : -1)"))
                {
                    for (var k = 0; k < exact.Count; k++)
                        _w.Line($"case {k}: return {KnownCaseHash(type, exact[k], assignable, level)};");

                    _w.Line("default: break;");
                }
            }
            else
            {
                foreach (var c in exact)
                    _w.Line($"if ({ExactTest("o", Type(c.TypeId))}) return {KnownCaseHash(type, c, assignable, level)};");
            }

                        foreach (var c in assignable.Where(c => !c.Hoistable))
                EmitAssignableCaseHash(type, c, level);

            _w.Line($"throw new {KnownTypes.GlobalUnknownTypeException}(o.GetType());");
        }
    }

        private void EmitAssignableCaseHash(TypeModel type, DispatchCase c, int level)
    {
        var target = Type(c.TypeId);
        var local = $"c{c.TypeId}";
        _w.Line($"if (o is {target.GlobalName} {local}) return {CaseHash(type, target, local, level, c.IsSameScc, isExact: false)};");
    }

    /// <summary>The hash of a known exact case: the case type's own rule, or the assignable case its type converts to.</summary>
    private string KnownCaseHash(TypeModel type, DispatchCase c, List<DispatchCase> assignable, int level)
    {
        if (c.ResolvedAssignable >= 0)
        {
            var a = assignable[c.ResolvedAssignable];
            var target = Type(a.TypeId);
            return CaseHash(type, target, AsCase(target, "o"), level, a.IsSameScc, isExact: false);
        }

        return CaseHash(type, Type(c.TypeId), "o", level, c.IsSameScc, isExact: true);
    }

    /// <summary>The hash of a dispatch case at the level the dispatch preserves: a same-SCC case keeps the level, any other is full.</summary>
    private string CaseHash(TypeModel dispatch, TypeModel target, string value, int level, bool sameScc, bool isExact)
    {
        if (target.IsObject) 
            return "1";

        var caseLevel = sameScc ? level : 1;
        switch (target.Kind)
        {
            case TypeKind.Leaf:
                var typed = isExact ? $"(({target.GlobalName}){value})" : value;
                return target.LeafRule == LeafRule.Custom 
                    ? $"{_model.CustomComparers[target.CustomComparerIndex].HolderName}.Value.GetHashCode({typed})" 
                    
                    // UserSimple and Default hash through LeafHash's direct GetHashCode() call, which is all the default comparer does.
                    : LeafHash(target, typed);

            case TypeKind.Class:
                if (target.Id == dispatch.Id) return $"{(caseLevel == 1 ? "HashMembers_" : "ShallowHashMembers_")}{target.ShortName}(o)";

                var cast = $"{KnownTypes.GlobalUnsafe}.As<{target.GlobalName}>({value})";
                return target.IsSealed
                    ? $"{(caseLevel == 1 ? "GetHashCode_" : "ShallowHashCode_")}{target.ShortName}({cast})" 
                    : $"{(caseLevel == 1 ? "HashMembers_" : "ShallowHashMembers_")}{target.ShortName}({cast})";

            case TypeKind.Struct:
                var unboxed = Unbox(target, value);
                return
                    $"{(caseLevel == 1 || !target.HasShallowHash ? "GetHashCode_" : "ShallowHashCode_")}{target.ShortName}({unboxed})";
            
            case TypeKind.Tuple:
                return
                    $"{(caseLevel == 1 || !target.HasShallowHash ? "GetHashCode_" : "ShallowHashCode_")}{target.ShortName}({KnownTypes.GlobalUnsafe}.As<{target.GlobalName}>({value}))";
            
            default:
                var operand = isExact ? target.IsValueType ? Unbox(target, value) : $"{KnownTypes.GlobalUnsafe}.As<{target.GlobalName}>({value})" : value;
                return
                    $"{(caseLevel == 1 || !target.HasShallowHash ? "GetHashCode_" : "ShallowHashCode_")}{target.ShortName}({operand})";
        }
    }

    // ----- ordered collections ------------------------------------------------------------------------------------------------

    private bool SpanAvailable(TypeModel type) => type.Kind switch
    {
        TypeKind.Array => _model.Capabilities.HasReadOnlySpan,
        TypeKind.List => _model.Capabilities is { HasReadOnlySpan: true, HasCollectionsMarshal: true },
        _ => false,
    };

    private static string SpanOf(TypeModel type, string value) => 
        type.Kind == TypeKind.List
            ? $"global::System.Runtime.InteropServices.CollectionsMarshal.AsSpan({value})"
            : value;

    private string ElementHashForContainer(TypeModel container, TypeModel element, string value)
        => HashOrOmit(element, value, 1, container.ElementIsSameScc) ?? "0";

    private void EmitArrayOrListCores(TypeModel type)
    {
        var element = Type(type.ElementTypeId);
        var p = Param(type);
        var count = type.Kind == TypeKind.Array ? "Length" : "Count";

        using (_w.Block($"private static bool Equals_{type.ShortName}({p} x, {p} y{StateParam(type)})"))
        {
            _w.Line($"if ({RefEq("x", "y")}) return true;");
            _w.Line($"if (x is null || y is null || x.{count} != y.{count}) return false;");
            EmitCycleGuard(type);

            if (SpanAvailable(type))
            {
                _spanCores.Add(element.Id);
                _w.Return($"Equals_SpanOf{element.ShortName}({SpanOf(type, "x")}, {SpanOf(type, "y")}{StateArg(type)})");
            }
            else
            {
                _w.Line($"int n = x.{count};");
                using (_w.For("n")) _w.Line($"if (!({Eq(element, "x[i]", "y[i]")})) return false;");
                _w.Return("true");
            }

        }

        // Level 1 hash.
        using (_w.Block($"private static int GetHashCode_{type.ShortName}({p} o)"))
        {
            _w.Line("if (o is null) return 0;");
            if (SpanAvailable(type) && _model.Capabilities.HasFrameworkSpanHelpers)
            {
                var ops = type.ElementIsSameScc ? $"{type.ShortName}ShallowOps" : $"{type.ShortName}Ops";
                _w.Return($"{KnownTypes.GlobalHashCode}.HashSpan<{element.GlobalName}, {ops}>({SpanOf(type, "o")})");
            }
            else
            {
                _w.Line($"{KnownTypes.GlobalHashCode}.Streaming h = default;");
                _w.Line($"int n = o.{count};");
                using (_w.For("n")) _w.Line($"h.Add({ElementHashForContainer(type, element, "o[i]")});");
                _w.Return("h.ToHashCode()");
            }

        }

        if (type.HasShallowHash)
            _w.Arrow($"private static int ShallowHashCode_{type.ShortName}({p} o)", $"o is null ? 0 : (o.{count} == 0 ? 1 : o.{count})");

        if (SpanAvailable(type) && _model.Capabilities.HasFrameworkSpanHelpers)
            EmitHashOps(type, element);

        _w.Line();
    }

    private void EmitHashOps(TypeModel container, TypeModel element)
    {
        var name = container.ElementIsSameScc ? $"{container.ShortName}ShallowOps" : $"{container.ShortName}Ops";
        using (_w.Block($"private struct {name} : {KnownTypes.GlobalHashOps}<{element.GlobalName}>"))
        {
            _w.Arrow($"public int GetHashCode({element.GlobalName} value)", ElementHashForContainer(container, element, "value"));
        }
    }

    private void EmitSpanCores(TypeModel element)
    {
        var needsState = element.NeedsState;
        var stateParam = needsState ? $", ref {KnownTypes.GlobalState} state" : string.Empty;
        var span = $"global::System.ReadOnlySpan<{element.GlobalName}>";
        using (_w.Block($"private static bool Equals_SpanOf{element.ShortName}({span} xs, {span} ys{stateParam})"))
        {
            _w.Line("if (xs.Length != ys.Length) return false;");
            if (element is { Kind: TypeKind.Leaf, DefaultCompatible: true, ImplementsIEquatable: true } && 
                element.LeafRule != LeafRule.Custom && element.LeafRule != LeafRule.Enum) _w.Return("global::System.MemoryExtensions.SequenceEqual(xs, ys)");
            else
            {
                using (_w.For("xs.Length")) _w.Line($"if (!({Eq(element, "xs[i]", "ys[i]")})) return false;");
                _w.Return("true");
            }

        }
        _w.Line();
    }

    private bool ImmutableSpans => _model.Capabilities is { HasImmutableArray: true, HasReadOnlySpan: true };

    private void EmitListInterfaceCores(TypeModel type)
    {
        var element = Type(type.ElementTypeId);
        var p = Param(type);
        var iface = type.CollectionInterfaceGlobalName.Length > 0 ? type.CollectionInterfaceGlobalName : type.GlobalName;

        using (_w.Block($"private static bool Equals_{type.ShortName}({p} x, {p} y{StateParam(type)})"))
        {
            EmitReferencePrelude();
            EmitSpanCapture(element, "x", "y");
            _w.Line($"{iface} xi = x;");
            _w.Line($"{iface} yi = y;");
            _w.Line("int count = xi.Count;");
            _w.Line("if (count != yi.Count) return false;");
            EmitCycleGuard(type);
            EmitSpanCompare(element);

            using (_w.For("count")) _w.Line($"if (!({Eq(element, "xi[i]", "yi[i]")})) return false;");
            _w.Return("true");
        }

        using (_w.Block($"private static int GetHashCode_{type.ShortName}({p} o)"))
        {
            _w.Line("if (o is null) return 0;");
            EmitSpanHash(type, element, "o");
            _w.Line($"{iface} oi = o;");
            _w.Line($"{KnownTypes.GlobalHashCode}.Streaming h = default;");
            _w.Line("int n = oi.Count;");
            using (_w.For("n")) _w.Line($"h.Add({ElementHashForContainer(type, element, "oi[i]")});");
            _w.Return("h.ToHashCode()");
        }

        if (type.HasShallowHash)
            _w.Arrow($"private static int ShallowHashCode_{type.ShortName}({p} o)", $"o is null ? 0 : ((({iface})o).Count == 0 ? 1 : (({iface})o).Count)");

        if (_model.Capabilities.HasFrameworkSpanHelpers)
            EmitHashOps(type, element);

        _w.Line();
    }

    /// <summary>
    /// The span each side of an interface-typed collection exposes, when it is an array, a list, or an immutable array,
    /// captured before anything reads the view. A default immutable array equals only another default one; nothing else
    /// may touch it, because its members throw.
    /// </summary>
    private void EmitSpanCapture(TypeModel element, string x, string y)
    {
        var capture = _model.Capabilities.HasFrameworkSpanHelpers || ImmutableSpans;
        if (capture)
        {
            _spanCores.Add(element.Id);
            var span = $"global::System.ReadOnlySpan<{element.GlobalName}>";
            _w.Line($"{span} {x}s = default;");
            _w.Line($"bool {x}Span = false;");
            _w.Line($"{span} {y}s = default;");
            _w.Line($"bool {y}Span = false;");
        }

        if (!_model.Capabilities.HasImmutableArray)
            return;

        var immutable = $"global::System.Collections.Immutable.ImmutableArray<{element.GlobalName}>";
        if (ImmutableSpans)
        {
            using (_w.Block($"if ({x} is {immutable} i{x})"))
            {
                _w.Line($"if (i{x}.IsDefault) return {y} is {immutable} i{y}d && i{y}d.IsDefault;");
                _w.Line($"{x}s = i{x}.AsSpan();");
                _w.Line($"{x}Span = true;");
            }

            using (_w.Block($"if ({y} is {immutable} i{y})"))
            {
                _w.Line($"if (i{y}.IsDefault) return false;");
                _w.Line($"{y}s = i{y}.AsSpan();");
                _w.Line($"{y}Span = true;");
            }
        }
        else
        {
            _w.Line($"bool {x}Default = {x} is {immutable} i{x} && i{x}.IsDefault;");
            _w.Line($"bool {y}Default = {y} is {immutable} i{y} && i{y}.IsDefault;");
            _w.Line($"if ({x}Default || {y}Default) return {x}Default && {y}Default;");
        }
    }

    /// <summary>Compares through the span core when both sides captured or expose a span; otherwise falls through.</summary>
    private void EmitSpanCompare(TypeModel element)
    {
        var helpers = _model.Capabilities.HasFrameworkSpanHelpers;
        if (!helpers && !ImmutableSpans)
            return;

        var xSpan = helpers ? $"(xSpan || {KnownTypes.GlobalCollections}.TryGetSpan(x, out xs))" : "xSpan";
        var ySpan = helpers ? $"(ySpan || {KnownTypes.GlobalCollections}.TryGetSpan(y, out ys))" : "ySpan";
        _w.Line($"if ({xSpan} && {ySpan}) return Equals_SpanOf{element.ShortName}(xs, ys{(element.NeedsState ? ", ref state" : string.Empty)});");
    }

    /// <summary>The hash of an interface-typed collection through its span, when it has one; otherwise falls through. A default immutable array hashes to 0.</summary>
    private void EmitSpanHash(TypeModel container, TypeModel element, string o)
    {
        var helpers = _model.Capabilities.HasFrameworkSpanHelpers;
        var ops = container.ElementIsSameScc ? $"{container.ShortName}ShallowOps" : $"{container.ShortName}Ops";
        var hashSpan = $"{KnownTypes.GlobalHashCode}.HashSpan<{element.GlobalName}, {ops}>";
        if (_model.Capabilities.HasImmutableArray)
        {
            var immutable = $"global::System.Collections.Immutable.ImmutableArray<{element.GlobalName}>";
            _w.Line(helpers && ImmutableSpans
                ? $"if ({o} is {immutable} io) return io.IsDefault ? 0 : {hashSpan}(io.AsSpan());"
                : $"if ({o} is {immutable} io && io.IsDefault) return 0;");
        }

        if (helpers)
            _w.Line($"if ({KnownTypes.GlobalCollections}.TryGetSpan({o}, out global::System.ReadOnlySpan<{element.GlobalName}> s)) return {hashSpan}(s);");
    }

    private void EmitEnumerableCores(TypeModel type)
    {
        var element = Type(type.ElementTypeId);
        var p = Param(type);
        var enumerable = $"global::System.Collections.Generic.IEnumerable<{element.GlobalName}>";

        using (_w.Block($"private static bool Equals_{type.ShortName}({p} x, {p} y{StateParam(type)})"))
        {
            EmitReferencePrelude();
            EmitSpanCapture(element, "x", "y");
            if (_model.Capabilities.HasFrameworkSpanHelpers || ImmutableSpans)
            {
                // Both sides have spans: their lengths decide, and no interface is consulted.
                EmitCycleGuard(type);
                EmitSpanCompare(element);
            }

            _w.Line($"int xCount = x is global::System.Collections.Generic.ICollection<{element.GlobalName}> xc ? xc.Count : (x is global::System.Collections.Generic.IReadOnlyCollection<{element.GlobalName}> xr ? xr.Count : -1);");
            _w.Line($"int yCount = y is global::System.Collections.Generic.ICollection<{element.GlobalName}> yc ? yc.Count : (y is global::System.Collections.Generic.IReadOnlyCollection<{element.GlobalName}> yr ? yr.Count : -1);");
            _w.Line("if (xCount >= 0 && yCount >= 0 && xCount != yCount) return false;");
            EmitCycleGuard(type);

            _w.Line("int n = 0;");
            using (_w.Block($"using (global::System.Collections.Generic.IEnumerator<{element.GlobalName}> ex = (({enumerable})x).GetEnumerator())"))
            {
                using (_w.Block($"using (global::System.Collections.Generic.IEnumerator<{element.GlobalName}> ey = (({enumerable})y).GetEnumerator())"))
                {
                    using (_w.Block("while (true)"))
                    {
                        _w.Line("bool mx = ex.MoveNext();");
                        _w.Line("bool my = ey.MoveNext();");
                        _w.Line("if (mx != my) return false;");
                        _w.Line("if (!mx) break;");
                        _w.Line($"{Param(element)} cx = ex.Current;");
                        _w.Line($"{Param(element)} cy = ey.Current;");
                        _w.Line($"if (!({Eq(element, "cx", "cy")})) return false;");
                        _w.Line("n++;");
                    }
                }
            }
            _w.Line("if ((xCount >= 0 && n != xCount) || (yCount >= 0 && n != yCount)) throw new global::System.InvalidOperationException(\"A collection enumerated a different number of elements than its Count advertised.\");");
            _w.Return("true");
        }

        using (_w.Block($"private static int GetHashCode_{type.ShortName}({p} o)"))
        {
            _w.Line("if (o is null) return 0;");
            EmitSpanHash(type, element, "o");
            _w.Line($"{KnownTypes.GlobalHashCode}.Streaming h = default;");
            using (_w.Block($"foreach ({element.GlobalName} e in ({enumerable})o)")) _w.Line($"h.Add({ElementHashForContainer(type, element, "e")});");
            _w.Return("h.ToHashCode()");
        }

        if (type.HasShallowHash)
        {
            using (_w.Block($"private static int ShallowHashCode_{type.ShortName}({p} o)"))
            {
                _w.Line("if (o is null) return 0;");
                _w.Line($"int count = o is global::System.Collections.Generic.ICollection<{element.GlobalName}> c ? c.Count : (o is global::System.Collections.Generic.IReadOnlyCollection<{element.GlobalName}> r ? r.Count : -1);");
                using (_w.Block("if (count < 0)"))
                {
                    _w.Line("count = 0;");
                    _w.Line($"foreach ({element.GlobalName} e in ({enumerable})o) count++;");
                }
                _w.Return("count == 0 ? 1 : count");
            }
        }

        if (_model.Capabilities.HasFrameworkSpanHelpers)
            EmitHashOps(type, element);

        _w.Line();
    }

    // ----- unordered collections -----------------------------------------------------------------------------------------------

    private void EmitUnorderedCores(TypeModel type)
    {
        var dictionary = type.Kind == TypeKind.Dictionary;
        var key = dictionary ? Type(type.KeyTypeId) : Type(type.ElementTypeId);
        var value = dictionary ? Type(type.ValueTypeId) : null;
        var elementName = dictionary ? $"global::System.Collections.Generic.KeyValuePair<{key.GlobalName}, {value!.GlobalName}>" : key.GlobalName;
        var p = Param(type);
        var iface = type.CollectionInterfaceGlobalName.Length > 0 ? type.CollectionInterfaceGlobalName : type.GlobalName;
        var ops = $"{type.ShortName}Ops";
        var concrete = dictionary
            ? $"global::System.Collections.Generic.Dictionary<{key.GlobalName}, {value!.GlobalName}>"
            : $"global::System.Collections.Generic.HashSet<{key.GlobalName}>";

        // The static type is the framework collection itself: no view, no runtime test, direct Count and enumerator.
        var isConcrete = type.GlobalName == concrete;

        // The key's rule is what EqualityComparer<K>.Default does, so a collection built on that comparer already
        // groups by the context's equality and can be walked through its own lookup, with no materialization or sort.
        var keyIsDefault = key is { Kind: TypeKind.Leaf, DefaultCompatible: true } && key.LeafRule != LeafRule.Custom;

        using (_w.Block($"private static bool Equals_{type.ShortName}({p} x, {p} y{StateParam(type)})"))
        {
            EmitReferencePrelude();
            string xs, ys;
            if (isConcrete)
            {
                xs = "x";
                ys = "y";
                _w.Line("int count = x.Count;");
                _w.Line("if (count != y.Count) return false;");
            }
            else
            {
                xs = "xi";
                ys = "yi";
                _w.Line($"{iface} xi = x;");
                _w.Line($"{iface} yi = y;");
                _w.Line("int count = xi.Count;");
                _w.Line("if (count != yi.Count) return false;");
            }

            EmitCycleGuard(type);

            if (keyIsDefault)
            {
                var (cx, cy) = isConcrete ? ("x", "y") : ("hx", "hy");
                var test = isConcrete
                    ? $"if ({DefaultComparerTest(key, "x.Comparer")} && {DefaultComparerTest(key, "y.Comparer")})"
                    : $"if (x is {concrete} hx && y is {concrete} hy && {DefaultComparerTest(key, "hx.Comparer")} && {DefaultComparerTest(key, "hy.Comparer")})";
                using (_w.Block(test))
                {
                    if (!dictionary)
                    {
                        _w.Return($"{cx}.SetEquals({cy})");
                    }
                    else
                    {
                        using (_w.Block($"foreach ({elementName} e in {cx})"))
                        {
                            _w.Line($"{Param(value!)} v;");
                            _w.Line($"if (!{cy}.TryGetValue(e.Key, out v) || !({Eq(value!, "e.Value", "v")})) return false;");
                        }

                        _w.Return("true");
                    }
                }
            }

            var call = dictionary
                ? $"{KnownTypes.GlobalUnordered}.DictionaryEquals<{key.GlobalName}, {value!.GlobalName}, {ops}>({xs}, {ys}, count, MaxUnorderedCollisionRun{StateArg(type)})"
                : $"{KnownTypes.GlobalUnordered}.SetEquals<{key.GlobalName}, {ops}>({xs}, {ys}, count, MaxUnorderedCollisionRun{StateArg(type)})";
            _w.Return(call);
        }

        // Ops struct: equality and full hash of one entry.
        var opsInterface = type.NeedsState ? KnownTypes.GlobalElementOps : KnownTypes.GlobalStatelessElementOps;
        using (_w.Block($"private struct {ops} : {opsInterface}<{elementName}>"))
        {
            var stateParam = type.NeedsState ? $", ref {KnownTypes.GlobalState} state" : string.Empty;
            var entryEq = dictionary
                ? $"{Eq(key, "a.Key", "b.Key")} && {Eq(value!, "a.Value", "b.Value")}"
                : Eq(key, "a", "b");
            _w.Arrow($"public bool Equals({elementName} a, {elementName} b{stateParam})", entryEq);
            _w.Arrow($"public int GetHashCode({elementName} a)", EntryHash(type, key, value, "a", forMatching: true));
        }

        // Level 1 hash: Combine(Count, sum of entry hashes) with empty-zero finalization.
        using (_w.Block($"private static int GetHashCode_{type.ShortName}({p} o)"))
        {
            _w.Line("if (o is null) return 0;");
            _w.Line("int sum = 0;");
            var entry = $"foreach ({elementName} e in {{0}}) {{{{ unchecked {{{{ sum += {EntryHash(type, key, value, "e", forMatching: false)}; }}}} }}}}";
            if (isConcrete)
            {
                _w.Line("int count = o.Count;");
                _w.Line(string.Format(entry, "o"));
            }
            else
            {
                _w.Line($"{iface} oi = o;");
                _w.Line("int count = oi.Count;");
                using (_w.Block($"if (o is {concrete} known)"))
                    _w.Line(string.Format(entry, "known"));
                using (_w.Block("else"))
                    _w.Line(string.Format(entry, $"(global::System.Collections.Generic.IEnumerable<{elementName}>)o"));
            }

            _w.Line($"int h = {KnownTypes.GlobalHashCode}.Combine(count, sum);");
            _w.Return("count == 0 && h == 0 ? 1 : h");
        }

        if (type.HasShallowHash)
            _w.Arrow($"private static int ShallowHashCode_{type.ShortName}({p} o)", isConcrete
                ? "o is null ? 0 : (o.Count == 0 ? 1 : o.Count)"
                : $"o is null ? 0 : ((({iface})o).Count == 0 ? 1 : (({iface})o).Count)");

        _w.Line();
    }

    /// <summary>
    /// True when a framework set or dictionary compares its keys the way the context does: the default comparer, or
    /// for string keys the ordinal comparer, which is the same equality under another instance.
    /// </summary>
    private static string DefaultComparerTest(TypeModel key, string comparer)
    {
        var isDefault = RefEq(comparer, $"{KnownTypes.GlobalEqualityComparer}<{key.GlobalName}>.Default");
        return key.GlobalName == "string"
            ? $"({isDefault} || {RefEq(comparer, "global::System.StringComparer.Ordinal")})"
            : isDefault;
    }

    /// <summary>
    /// The hash of one set element or dictionary pair.
    /// Matching uses full element hashes; the container hash uses the SCC level.
    /// </summary>
    private string EntryHash(TypeModel container, TypeModel key, TypeModel? value, string entry, bool forMatching)
    {
        if (value is null) return forMatching ? HashOrOmit(key, entry, 1, sameScc: false) ?? "0" : ElementHashForContainer(container, key, entry);

        var k = forMatching ? HashOrOmit(key, $"{entry}.Key", 1, sameScc: false) ?? "0" : HashOrOmit(key,
            $"{entry}.Key", 1, container.KeyIsSameScc) ?? "0";
        var v = forMatching ? HashOrOmit(value, $"{entry}.Value", 1, sameScc: false) ?? "0" : HashOrOmit(value,
            $"{entry}.Value", 1, container.ValueIsSameScc) ?? "0";
        return $"{KnownTypes.GlobalHashCode}.Combine({k}, {v})";
    }

    // ----- products -------------------------------------------------------------------------------------------------------------

    private static string TupleItem(int index)
    {
        var path = string.Empty;
        while (index >= 7)
        {
            path += "Rest.";
            index -= 7;
        }

        return $"{path}Item{index + 1}";
    }

    private void EmitProductCores(TypeModel type)
    {
        var reference = type.Kind == TypeKind.Tuple;
        var p = reference ? Param(type) : type.GlobalName;
        List<(TypeModel Type, string Path, bool SameScc)> items = new(type.Kind == TypeKind.KeyValuePair ? 2 : type.ItemTypeIds.Count);
        if (type.Kind == TypeKind.KeyValuePair)
        {
            items.Add((Type(type.KeyTypeId), "Key", type.KeyIsSameScc));
            items.Add((Type(type.ValueTypeId), "Value", type.ValueIsSameScc));
        }
        else
            items.AddRange(type.ItemTypeIds.Select((t, i) => (Type(t), TupleItem(i), type.ItemsAreSameScc[i])));

        using (_w.Block($"private static bool Equals_{type.ShortName}({p} x, {p} y{StateParam(type)})"))
        {
            if (reference)
            {
                EmitReferencePrelude();
                EmitCycleGuard(type);
            }

            EmitPredicates(items, i => Eq(i.Type, $"x.{i.Path}", $"y.{i.Path}"), terminalReturnTrue: true);
        }

        for (var level = 1; level >= (type.HasShallowHash ? 0 : 1); level--)
        {
            var name = (level == 1 ? "GetHashCode_" : "ShallowHashCode_") + type.ShortName;
            using (_w.Block($"private static int {name}({p} o)"))
            {
                if (reference) _w.Line("if (o is null) return 0;");

                                var inputs = new List<string>(items.Count);
                var k = 0;
                foreach (var (itemType, path, sameScc) in items)
                    HashWords(itemType, $"o.{path}", level, sameScc, $"w{k++}", inputs);

                _w.Return(Combine(inputs));
            }
        }

        _w.Line();
    }

    // ----- accessors ------------------------------------------------------------------------------------------------------------

    private void EmitAccessors()
    {
        var emitted = new HashSet<string>(StringComparer.Ordinal);
        var generic = new Dictionary<string, List<MemberModel>>(StringComparer.Ordinal);
        foreach (var type in _types)
        {
            foreach (var member in type.Members)
            {
                if (member.Access != MemberAccess.UnsafeAccessor) continue;

                if (member.GenericAccessor)
                {
                    if (!generic.TryGetValue(member.GenericHolderName, out var list))
                        generic[member.GenericHolderName] = list = [];

                    if (list.All(m => m.AccessorName != member.AccessorName))
                        list.Add(member);

                    continue;
                }

                if (!emitted.Add(member.AccessorName))
                    continue;

                var fieldType = Type(member.TypeId);
                var receiver = member.DeclaringTypeIsValueType ? $"ref {member.DeclaringTypeGlobalName} o" : $"{member.DeclaringTypeGlobalName} o";
                _w.Line($"[{KnownTypes.GlobalUnsafeAccessor}({KnownTypes.GlobalUnsafeAccessorKind}.Field, Name = \"{member.FieldMetadataName}\")]");
                _w.Line($"private static extern ref {Param(fieldType)} {member.AccessorName}({receiver});");
            }
        }

        if (emitted.Count > 0)
            _w.Line();

        // The runtime maps the holder's class type parameters onto the declaring type's,
        // so one holder per definition carries every accessor of that definition;
        // call sites name the constructed arguments.
        foreach (var holder in generic.OrderBy(h => h.Key, StringComparer.Ordinal))
        {
            var first = holder.Value[0];
            using (_w.Block($"private static class {holder.Key}{first.GenericTypeParameters}{first.GenericConstraints}"))
            {
                foreach (var member in holder.Value.OrderBy(m => m.AccessorName, StringComparer.Ordinal))
                {
                    var openReceiver = member.DeclaringTypeIsValueType ? $"ref {member.OpenDeclaringTypeGlobalName} o" : $"{member.OpenDeclaringTypeGlobalName} o";
                    _w.Line($"[{KnownTypes.GlobalUnsafeAccessor}({KnownTypes.GlobalUnsafeAccessorKind}.Field, Name = \"{member.FieldMetadataName}\")]");
                    _w.Line($"internal static extern ref {member.OpenFieldTypeGlobalName} {member.AccessorName}({openReceiver});");
                }

            }
            _w.Line();
        }
    }

    private void EmitAccessorHolders()
    {
        foreach (var holder in _model.AccessorHolders)
        {
            if (_model.Capabilities.HasRequiresUnreferencedCode)
                _w.Line("[global::System.Diagnostics.CodeAnalysis.RequiresUnreferencedCode(\"Reads private fields by name through reflection-built delegates.\")]");

            if (_model.Capabilities.HasRequiresDynamicCode)
                _w.Line("[global::System.Diagnostics.CodeAnalysis.RequiresDynamicCode(\"Compiles expression trees for private field access.\")]");

            using (_w.Block($"private static class {holder.HolderName}"))
            {
                _w.Line($"static {holder.HolderName}() {{ }}");
                foreach (var member in holder.Members)
                {
                    var fieldType = Type(member.TypeId);
                    var getter = $"{KnownTypes.GlobalFieldGetter}<{holder.DeclaringTypeGlobalName}, {Param(fieldType)}>";
                    _w.Line($"private static readonly {getter} s_{member.AccessorName} = {KnownTypes.GlobalReflection}.CreateFieldGetter<{holder.DeclaringTypeGlobalName}, {Param(fieldType)}>(typeof({holder.DeclaringTypeGlobalName}), \"{member.FieldMetadataName}\");");
                    _w.Line(holder.DeclaringTypeIsValueType
                        ? $"internal static {Param(fieldType)} {member.AccessorName}(ref {holder.DeclaringTypeGlobalName} o) => s_{member.AccessorName}(ref o);"
                        : $"internal static {Param(fieldType)} {member.AccessorName}({holder.DeclaringTypeGlobalName} o) => s_{member.AccessorName}(ref o);");
                }

            }
            _w.Line();
        }
    }

    private void EmitCustomComparerHolders()
    {
        foreach (var custom in _model.CustomComparers)
        {
            var fieldType = custom.HolderTypedAsComparer ? custom.ComparerTypeGlobalName : $"{KnownTypes.GlobalIEqualityComparer}<{custom.TargetTypeGlobalName}>";
            using (_w.Block($"private static class {custom.HolderName}"))
            {
                _w.Line($"static {custom.HolderName}() {{ }}");
                _w.Line($"internal static readonly {fieldType} Value = {custom.AcquisitionExpression};");
            }
            _w.Line();
        }
    }
