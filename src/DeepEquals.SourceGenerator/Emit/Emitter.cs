/// <summary>
/// A straight walk over the model.
/// No decisions are made here that the model does not already record.
/// </summary>
internal sealed class Emitter
{
    private const int MaxCombineArity = 32;

    private readonly ContextModel _model;
    private readonly CancellationToken _cancellationToken;
    private readonly TypeModel[] _types;
    private readonly HashSet<int> _spanCores = [];
    private readonly List<(TypeModel Type, List<DispatchCase> Exact)> _pendingDispatchHolders = [];

    /// <summary>The writer of the file being emitted; every emit method writes here, and the file loop swaps it.</summary>
    private CodeWriter _w;

    private Emitter(ContextModel model, CancellationToken cancellationToken)
    {
        _model = model;
        _cancellationToken = cancellationToken;
        _types = model.Types.ToArray();
        _w = new CodeWriter(0);
    }

    /// <summary>
    /// The files of a context, the layout System.Text.Json uses: the context file carries what is shared, and each
    /// closure type that has anything to emit gets a file of its own.
    /// </summary>
    public static IReadOnlyList<GeneratedFile> Emit(ContextModel model, CancellationToken cancellationToken)
    {
        var emitter = new Emitter(model, cancellationToken);
        return emitter.EmitFiles();
    }

    private TypeModel Type(int id) => _types[id];

    private bool Annotations => _model.Capabilities.NullableAnnotations;

    // ----- file ---------------------------------------------------------------------------------------------------------

    /// <summary>The package version of the generator, read once from the assembly's informational version without its build metadata.</summary>
    private static readonly string GeneratorVersion = ReadGeneratorVersion();

    private static string ReadGeneratorVersion()
    {
        var assembly = typeof(Emitter).Assembly;
        var informational = assembly
            .GetCustomAttributes<AssemblyInformationalVersionAttribute>()
            .Select(x => x.InformationalVersion)
            .FirstOrDefault();
        if (!string.IsNullOrEmpty(informational))
        {
            var plus = informational.IndexOf('+');
            return plus < 0 ? informational : informational[..plus];
        }

        return assembly.GetName().Version?.ToString(3) ?? "1.0.0";
    }

    /// <summary>The header template, an embedded resource with <c>{{placeholders}}</c>, read once and split into lines.</summary>
    private static readonly string[] HeaderTemplate = ReadHeaderTemplate();

    private static string[] ReadHeaderTemplate()
    {
        using var stream = typeof(Emitter).Assembly.GetManifestResourceStream("DeepEquals.SourceGenerator.Templates.AutoGeneratedHeader.cs");
        if (stream is null)
            throw new InvalidOperationException("The embedded header template 'Templates/AutoGeneratedHeader.cs' is missing from the generator assembly.");

        using var reader = new System.IO.StreamReader(stream);
        return reader.ReadToEnd().Replace("\r\n", "\n").TrimEnd('\n').Split('\n');
    }

    private const string CommentIndent = "    ";

    /// <summary>
    /// A name for the block comment: no <c>global::</c>, and no <c>*/</c> that would end the comment early.
    /// </summary>
    private static string Display(string globalName) => 
        globalName.Replace("global::", string.Empty).Replace("*/", "* /");

    /// <summary>
    /// One indented line per entry, or a single "none" line,
    /// for a list placeholder inside the header's block comment.
    /// </summary>
    private static string CommentList(IEnumerable<string> entries, string none = "none")
    {
        var lines = entries.ToArray();
        return lines.Length == 0 
            ? CommentIndent + none 
            : string.Join("\n", lines.Select(l => CommentIndent + l));
    }

    /// <summary>
    /// Every value the header template can ask for, computed from the model alone so output stays deterministic.
    /// The context file lists the whole closure; a type file lists the one type it holds.
    /// </summary>
    private Dictionary<string, string> HeaderValues(TypeModel? single)
    {
        var contextName = _model.Namespace.Length > 0 ? $"{_model.Namespace}.{_model.Name}" : _model.Name;
        var c = _model.Capabilities;
        var o = _model.Options;

        string KindLabel(TypeModel t) => t.Kind switch
        {
            TypeKind.Leaf => t.LeafRule switch
            {
                LeafRule.Custom => "leaf, custom comparer",
                LeafRule.UserSimple => "leaf, [SimpleType]",
                LeafRule.Enum => "leaf, enum",
                _ => "leaf, built-in",
            },
            TypeKind.Nullable => "nullable wrapper",
            TypeKind.Class => t.IsSealed ? "class, compared by members" : "class, compared by members, dispatches to derived types",
            TypeKind.Struct => "struct, compared by members",
            TypeKind.Dispatch => t.IsObject 
                ? "object, dispatches on runtime type"
                : t.IsInterface ? "interface, dispatches on runtime type" : "abstract class, dispatches on runtime type",
            TypeKind.Array or TypeKind.List or TypeKind.ImmutableArray or TypeKind.ArraySegment or TypeKind.Memory or TypeKind.ListInterface or TypeKind.EnumerableInterface => 
                "ordered collection",
            TypeKind.Set => "set, unordered",
            TypeKind.Dictionary => "dictionary, unordered",
            TypeKind.KeyValuePair or TypeKind.ValueTuple or TypeKind.Tuple => "product, compared item by item",
            _ => t.Kind.ToString().ToLowerInvariant(),
        };

        var wrappers = _types.Where(t => t.EmitWrapper).ToList();
        var typeCount = _types.Length.ToString(System.Globalization.CultureInfo.InvariantCulture);
        var wrapperCount = wrappers.Count.ToString(System.Globalization.CultureInfo.InvariantCulture);
        string TypeLine(TypeModel t)
        {
            var note = !t.EmitWrapper ? "; no public comparer" : !t.EmitConvenienceProperty ? "; convenience property omitted" : string.Empty;
            return $"{Display(t.GlobalName)}  ({KindLabel(t)}{note})";
        }

        var closureHeading = single is null
            ? $"Closure ({typeCount} types, {wrapperCount} public comparers)"
            : $"Type (one of {typeCount} in the closure; {_model.HintNamePrefix}.g.cs lists them all)";
        var closure = single is null ? CommentList(wrappers.Select(TypeLine)) : CommentList([TypeLine(single)]);

        (string Name, bool Present)[] capabilities =
        [
            ("ReadOnlySpan<T>", c.HasReadOnlySpan),
            ("Memory<T>", c.HasMemory),
            ("CollectionsMarshal.AsSpan", c.HasCollectionsMarshal),
            ("MemoryMarshal", c.HasMemoryMarshal),
            ("IReadOnlySet<T>", c.HasIReadOnlySet),
            ("ImmutableArray<T>", c.HasImmutableArray),
            ("[UnsafeAccessor]", c.HasUnsafeAccessor),
            ("[UnsafeAccessor] on generic types", c.HasGenericUnsafeAccessor),
            ("framework TryGetSpan/HashSpan", c.HasFrameworkSpanHelpers),
            ("framework Hash(Int128)", c.HasFrameworkHash128),
            ("Nullable.GetValueRefOrDefaultRef", c.HasNullableGetValueRefOrDefaultRef),
            ("BitConverter.SingleToInt32Bits", c.HasSingleToInt32Bits),
            ("decimal.GetBits(Span<int>)", c.HasDecimalGetBitsSpan),
            ("[RequiresUnreferencedCode]", c.HasRequiresUnreferencedCode),
            ("[RequiresDynamicCode]", c.HasRequiresDynamicCode),
            ("[UnconditionalSuppressMessage]", c.HasUnconditionalSuppressMessage)
        ];

        var suppressed = new HashSet<string>(_model.SuppressedDiagnosticIds, StringComparer.Ordinal) 
            { "CS0162", "CS0168", "CS0219", "CS0108", "CS1591", "CS8019" };

        return new Dictionary<string, string>(StringComparer.Ordinal)
        {
            ["Version"] = GeneratorVersion,
            ["ContextName"] = contextName,
            ["ContextShortName"] = _model.Name,
            ["ContextAccessibility"] = _model.Accessibility,
            ["Roots"] = CommentList(_types.Where(t => t.IsRoot).Select(t => Display(t.GlobalName))),
            ["TypeCount"] = typeCount,
            ["WrapperCount"] = wrapperCount,
            ["ClosureHeading"] = closureHeading,
            ["Closure"] = closure,
            ["CustomComparers"] = CommentList(_model.CustomComparers.Select(cc => $"{Display(cc.TargetTypeGlobalName)}  by {Display(cc.ComparerTypeGlobalName)}{(cc.HandleNulls ? ", handles null itself" : string.Empty)}")),
            ["UnsafeTypes"] = CommentList(_types.Where(t => t.IsUnsafe && t.EmitWrapper).Select(t => Display(t.GlobalName))),
            ["MaxSwitchCases"] = o.MaxSwitchCases.ToString(System.Globalization.CultureInfo.InvariantCulture),
            ["MaxUnorderedCollisionRun"] = o.MaxUnorderedCollisionRun.ToString(System.Globalization.CultureInfo.InvariantCulture),
            ["MaxComparisonPairs"] = o.MaxComparisonPairs.ToString("N0", System.Globalization.CultureInfo.InvariantCulture),
            ["MaxBinaryExpressionArity"] = o.MaxBinaryExpressionArity.ToString(System.Globalization.CultureInfo.InvariantCulture),
            ["StructPassByValueMaxByteSize"] = o.StructPassByValueMaxByteSize.ToString(System.Globalization.CultureInfo.InvariantCulture),
            ["ExcludeInterfacesByPrefix"] = o.ExcludeInterfacesByPrefix.Count == 0 ? "(none)" : string.Join(", ", o.ExcludeInterfacesByPrefix),
            ["LanguageVersion"] = $"{c.LanguageVersion / 100}.{c.LanguageVersion % 100}",
            ["CapabilitiesPresent"] = string.Join(", ", capabilities.Where(x => x.Present).Select(x => x.Name)).OrDefault("(none)"),
            ["CapabilitiesAbsent"] = string.Join(", ", capabilities.Where(x => !x.Present).Select(x => x.Name)).OrDefault("(none)"),
            ["Diagnostics"] = CommentList(_model.Diagnostics.Select(d => 
                $"{d.Descriptor.Id}: {string.Format(System.Globalization.CultureInfo.InvariantCulture, d.Descriptor.MessageFormat.ToString(System.Globalization.CultureInfo.InvariantCulture), d.Arguments.Cast<object>().ToArray()).Replace("*/", "* /")}")),
            ["SuppressedDiagnostics"] = string.Join(", ", suppressed.OrderBy(s => s, StringComparer.Ordinal)),
            ["NullableDirective"] = Annotations
                ? "// Annotations only: generated code declares nullability for its callers but opts out of flow analysis,\n// so the consuming project's warning policy cannot fail the build on emitted source.\n#nullable enable annotations\n"
                : string.Empty,
        };
    }

    private void EmitHeader(Dictionary<string, string> values)
    {
        foreach (var templateLine in HeaderTemplate)
        {
            var line = values.Aggregate(
                templateLine,
                (current, value) => current.Replace("{{" + value.Key + "}}", value.Value));

            if (line.Length == 0 && templateLine.Length > 0)
                continue; // a placeholder that expanded to nothing leaves no blank line behind

            foreach (var part in line.Split('\n'))
                _w.Line(part);
        }
    }

    /// <summary>
    /// One file being written. Its writer stays open until every body is complete, because a span core lands in
    /// its element's file only once the containers that call it have been emitted.
    /// </summary>
    private sealed class OpenFile
    {
        public OpenFile(string hintName, CodeWriter writer, int bodyStart, int closes)
        {
            HintName = hintName;
            Writer = writer;
            BodyStart = bodyStart;
            Closes = closes;
        }

        public string HintName { get; }

        public CodeWriter Writer { get; }

        /// <summary>The writer's length once the skeleton is open; a file whose body never grew past it is not emitted.</summary>
        public int BodyStart { get; }

        /// <summary>The blocks opened above the class body: namespace, containing types and the context class itself.</summary>
        public int Closes { get; }
    }

    private List<GeneratedFile> EmitFiles()
    {
        // Roslyn compares hint names case-insensitively, so two types differing only by case share a stem.
        var hintNames = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var contextFile = Open($"{_model.HintNamePrefix}.g.cs", HeaderValues(null), 4096 + _types.Length * 256);
        hintNames.Add(contextFile.HintName);

        var typeFiles = new OpenFile[_types.Length];
        foreach (var type in _types)
        {
            _cancellationToken.ThrowIfCancellationRequested();
            var stem = $"{_model.HintNamePrefix}.{type.ShortName}";
            var hintName = $"{stem}.g.cs";
            for (var n = 2; !hintNames.Add(hintName); n++)
                hintName = $"{stem}_{n}.g.cs";

            var file = typeFiles[type.Id] = Open(hintName, HeaderValues(type), 4096 + 2048);
            _w = file.Writer;
            EmitKinds(type);
            EmitConvenienceProperty(type);
            if (type.EmitWrapper)
                EmitWrapper(type);

            EmitCores(type);
            EmitDispatchHolders();
        }

        // Span cores are requested by the containers emitted above and belong to the element they compare.
        foreach (var element in _spanCores.OrderBy(i => i))
        {
            _w = typeFiles[element].Writer;
            EmitSpanCores(Type(element));
        }

        _w = contextFile.Writer;
        EmitConstants();
        EmitLookup();
        EmitAccessors();
        EmitAccessorHolders();
        EmitCustomComparerHolders();

        var files = new List<GeneratedFile>(_types.Length + 1) { Close(contextFile)! };
        foreach (var file in typeFiles)
        {
            if (Close(file) is { } generated)
                files.Add(generated);
        }

        return files;
    }

    /// <summary>The header and the skeleton down to the context's partial class, with the writer left inside it.</summary>
    private OpenFile Open(string hintName, Dictionary<string, string> headerValues, int capacity)
    {
        _w = new CodeWriter(capacity);
        EmitHeader(headerValues);
        _w.Line();

        var closes = 0;
        if (_model.Namespace.Length > 0)
        {
            _w.Open($"namespace {_model.Namespace}");
            closes++;
        }

        foreach (var containing in _model.ContainingTypes)
        {
            _w.Open($"partial class {containing}");
            closes++;
        }

        _w.Open($"{_model.Accessibility} partial class {_model.Name}");
        return new OpenFile(hintName, _w, _w.Length, closes + 1);
    }

    /// <summary>Closes the skeleton and returns the file, or null when nothing was written into the class.</summary>
    private static GeneratedFile? Close(OpenFile file)
    {
        if (file.Writer.Length == file.BodyStart)
            return null;

        for (var i = 0; i < file.Closes; i++)
            file.Writer.Close();

        return new GeneratedFile(file.HintName, file.Writer.ToString());
    }

    private void EmitConstants()
    {
        _w.Line($"private const int MaxComparisonPairs = {_model.Options.MaxComparisonPairs};");
        _w.Line($"private const int MaxUnorderedCollisionRun = {_model.Options.MaxUnorderedCollisionRun};");
        _w.Line();
    }

    /// <summary>The cycle-guard kinds of a type, read only by its own cores.</summary>
    private void EmitKinds(TypeModel type)
    {
        if (!type.IsGuarded && !type.BoxedAdapterGuarded)
            return;

        if (type.IsGuarded)
            _w.Line($"private const int Kind_{type.ShortName} = {type.GuardKind};");

        if (type.BoxedAdapterGuarded)
            _w.Line($"private const int Kind_Boxed_{type.ShortName} = {type.BoxedGuardKind};");

        _w.Line();
    }

    private void EmitLookup()
    {
        var mapped = _types.Where(t => t.EmitWrapper).ToList();
        using (_w.Block("private static class ComparerMap"))
        {
            _w.Line("static ComparerMap() { }");
            _w.Line($"internal static readonly global::System.Collections.Generic.Dictionary<{KnownTypes.GlobalType}, object> Value = Build();");
            using (_w.Block($"private static global::System.Collections.Generic.Dictionary<{KnownTypes.GlobalType}, object> Build()"))
            {
                _w.Line($"global::System.Collections.Generic.Dictionary<{KnownTypes.GlobalType}, object> map = new global::System.Collections.Generic.Dictionary<{KnownTypes.GlobalType}, object>({mapped.Count});");
                foreach (var type in mapped)
                    _w.Line($"map.Add(typeof({type.GlobalName}), {type.ShortName}EqualityComparer.Instance);");

                _w.Return("map");
            }
        }
        _w.Line();
                using (_w.Block("private static class Cache<T>"))
            _w.Line($"internal static readonly {KnownTypes.GlobalIEqualityComparer}<T>{Q()} Value = LookupEqualityComparer<T>(ComparerMap.Value);");
        _w.Line();
        EmitUnsafeAttributes(_model.HasUnsafeTypes);
        _w.Arrow(
            $"public static {KnownTypes.GlobalIEqualityComparer}<T> GetEqualityComparer<T>()", 
            "RequireEqualityComparer<T>(Cache<T>.Value)");
        _w.Line();
    }

    private void EmitConvenienceProperty(TypeModel type)
    {
        if (!type.EmitConvenienceProperty)
            return;

        if (type.IsUnsafe)
        {
            // The attributes belong on the getter: RequiresUnreferencedCode targets methods, not properties.
            using (_w.Block($"{type.Accessibility} static {type.ShortName}EqualityComparer {Identifier(type.ShortName)}"))
            {
                EmitUnsafeAttributes(true);
                _w.Arrow("get", $"{type.ShortName}EqualityComparer.Instance");
            }
        }
        else
        {
            _w.Arrow(
                $"{type.Accessibility} static {type.ShortName}EqualityComparer {Identifier(type.ShortName)}",
                $"{type.ShortName}EqualityComparer.Instance");
        }

        _w.Line();
    }

    private void EmitUnsafeAttributes(bool unsafeType)
    {
        if (!unsafeType) 
            return;

        if (_model.Capabilities.HasRequiresUnreferencedCode)
            _w.Line("[global::System.Diagnostics.CodeAnalysis.RequiresUnreferencedCode(\"This comparer reads private fields through reflection-built delegates; trimming can remove them.\")]");

        if (_model.Capabilities.HasRequiresDynamicCode) 
            _w.Line("[global::System.Diagnostics.CodeAnalysis.RequiresDynamicCode(\"This comparer compiles expression trees for private field access.\")]");
    }

    private void EmitSuppressions(TypeModel type)
    {
        if (!_model.Capabilities.HasUnconditionalSuppressMessage || 
            type.Members.All(m => m.Access != MemberAccess.Delegate)) 
            return;

        _w.Line("[global::System.Diagnostics.CodeAnalysis.UnconditionalSuppressMessage(\"Trimming\", \"IL2026\", Justification = \"The warning is surfaced on the context's convenience property and GetEqualityComparer<T>().\")]");
        _w.Line("[global::System.Diagnostics.CodeAnalysis.UnconditionalSuppressMessage(\"AOT\", \"IL3050\", Justification = \"The warning is surfaced on the context's convenience property and GetEqualityComparer<T>().\")]");
    }

    /// <summary>Suppressions for a method, then the method itself: the attributes and what they decorate are one unit.</summary>
    private IDisposable Method(TypeModel type, string signature)
    {
        EmitSuppressions(type);
        return _w.Block(signature);
    }

    /// <summary>Same reference is equal and one null is not; every reference-type Equals_ starts here.</summary>
    private void EmitReferencePrelude()
    {
        _w.Line($"if ({RefEq("x", "y")}) return true;");
        _w.Line("if (x is null || y is null) return false;");
    }

    /// <summary>
    /// The cycle guard, for the types that need one: a pair already being compared is taken as equal, which is what
    /// bounds the recursion. The boxed adapter has its own kind, and its own reason to be guarded.
    /// </summary>
    private void EmitCycleGuard(TypeModel type, bool boxed = false)
    {
        if (!(boxed ? type.BoxedAdapterGuarded : type.IsGuarded)) 
            return;

        _w.Line($"if (!state.TryEnter(Kind_{(boxed ? "Boxed_" : string.Empty)}{type.ShortName}, x, y)) return true;");
    }

